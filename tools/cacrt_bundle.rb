#!/usr/bin/env ruby
# frozen_string_literal: true
#
# Builds config/cacrt_fmrb.pem, the CA bundle the ESP32 terminals trust for
# HTTPS (doc/ca_bundle/plan.md). It is ESP-IDF's "full" bundle -- the same
# inputs IDF concatenates for CONFIG_MBEDTLS_CERTIFICATE_BUNDLE_DEFAULT_FULL
# (cacrt_all.pem + cacrt_local.pem) -- minus the names listed in
# config/cacrt_exclude.txt. The sdkconfig.defaults of the WiFi boards switch
# the default bundle off and point CONFIG_MBEDTLS_CUSTOM_CERTIFICATE_BUNDLE_PATH
# here, so this file is the whole trust store of the device.
#
# IDF lives only in the build image, so the inputs are copied out of it with
# docker. The output has no timestamp: the same inputs give the same bytes.
#
#   ruby tools/cacrt_bundle.rb --image <build image>      # rake certs:bundle
#   ruby tools/cacrt_bundle.rb --check-bin <x509_crt_bundle>
#       compares the binary bundle an IDF build generated with the PEM here
#       (rake certs:check_build)

require "digest"
require "open3"
require "openssl"
require "optparse"
require "tmpdir"

module CacrtBundle
  ROOT          = File.expand_path("..", __dir__)
  EXCLUDE_FILE  = File.join(ROOT, "config", "cacrt_exclude.txt")
  OUTPUT_FILE   = File.join(ROOT, "config", "cacrt_fmrb.pem")
  IDF_BUNDLE_DIR = "components/mbedtls/esp_crt_bundle"
  # The line of IDF's components/mbedtls/CMakeLists.txt that defines the full
  # bundle. If IDF ever builds it from something else, stop rather than
  # silently produce a bundle that differs from what "full" means.
  FULL_LINE = "list(APPEND crt_paths ${DEFAULT_CRT_DIR}/cacrt_all.pem ${DEFAULT_CRT_DIR}/cacrt_local.pem)"
  INPUTS = %w[cacrt_all.pem cacrt_local.pem].freeze
  BEGIN_LINE = "-----BEGIN CERTIFICATE-----"
  END_LINE   = "-----END CERTIFICATE-----"

  class Error < StandardError; end

  Entry = Struct.new(:name, :underline, :pem, keyword_init: true)

  module_function

  # Reads the exclude list: one name per line, '#' starts a comment.
  def read_exclude(text)
    text.each_line.map { |l| l.sub(/#.*/, "").strip }.reject(&:empty?)
  end

  # Splits a curl/mk-ca-bundle style PEM file into entries. A certificate's
  # name is the line above its '====' underline; a certificate without one
  # (allowed in cacrt_local.pem) gets nil. The PEM text is kept byte for byte.
  def parse_pem(text)
    lines = text.lines.map(&:chomp)
    entries = []
    i = 0
    while i < lines.size
      if lines[i] == BEGIN_LINE
        j = i
        j += 1 while j < lines.size && lines[j] != END_LINE
        raise Error, "unterminated certificate at line #{i + 1}" if j >= lines.size
        name = underline = nil
        if i >= 2 && lines[i - 1].match?(/\A=+\z/) && !lines[i - 2].strip.empty?
          name = lines[i - 2]
          underline = lines[i - 1]
        end
        entries << Entry.new(name: name, underline: underline, pem: lines[i..j].join("\n") + "\n")
        i = j + 1
      else
        i += 1
      end
    end
    entries
  end

  # Drops the excluded names. Every excluded name must match exactly one
  # entry: a misspelt name must not pass as "removed".
  def exclude(entries, names)
    names.each do |n|
      hits = entries.count { |e| e.name == n }
      raise Error, "excluded name not found in the IDF bundle: #{n.inspect}" if hits.zero?
      raise Error, "excluded name matches #{hits} certificates: #{n.inspect}" if hits > 1
    end
    entries.reject { |e| names.include?(e.name) }
  end

  def mozilla_date(text)
    text[/^## Certificate data from Mozilla as of: (.+)$/, 1]
  end

  def render(entries:, idf_version:, sources:, source_count:, excluded:, mozilla:)
    out = +""
    out << "##\n"
    out << "## Family mruby CA certificate bundle (config/cacrt_fmrb.pem)\n"
    out << "##\n"
    out << "## Generated by `rake certs:bundle` (tools/cacrt_bundle.rb). Do not edit\n"
    out << "## by hand: change config/cacrt_exclude.txt and run it again.\n"
    out << "##\n"
    out << "## ESP-IDF #{idf_version} \"full\" certificate bundle\n"
    out << "## (#{IDF_BUNDLE_DIR}) minus the excluded names below.\n"
    sources.each do |file, sha|
      out << "##   #{file}  sha256 #{sha}\n"
    end
    out << "## Certificate data from Mozilla as of: #{mozilla} (MPL-2.0)\n" if mozilla
    out << "##\n"
    out << "## Certificates: #{source_count} in the source, #{excluded.size} excluded, #{entries.size} here\n"
    out << "## Excluded:\n"
    excluded.each { |n| out << "##   #{n}\n" }
    out << "##\n"
    entries.each do |e|
      out << "\n"
      if e.name
        out << e.name << "\n" << e.underline << "\n"
      end
      out << e.pem
    end
    out
  end

  # Copies the inputs, IDF's mbedtls CMakeLists and its version header out of
  # the build image into dir.
  def fetch_from_image(image, dir)
    files = INPUTS.map { |f| "$IDF_PATH/#{IDF_BUNDLE_DIR}/#{f}" }
    files << "$IDF_PATH/components/mbedtls/CMakeLists.txt"
    files << "$IDF_PATH/components/esp_common/include/esp_idf_version.h"
    script = "cp #{files.join(' ')} /out/"
    cmd = ["docker", "run", "--rm", "--user", "#{Process.uid}:#{Process.gid}",
           "-e", "HOME=/tmp", "-v", "#{dir}:/out", image, "bash", "-c", script]
    # The image's entrypoint prints the IDF environment banner; show it only
    # when something went wrong.
    log, status = Open3.capture2e(*cmd)
    raise Error, "docker failed to copy the IDF bundle out of #{image}:\n#{log}" unless status.success?
  end

  def idf_version(header)
    v = %w[MAJOR MINOR PATCH].map do |k|
      header[/#define ESP_IDF_VERSION_#{k}\s+(\d+)/, 1] or raise Error, "no ESP_IDF_VERSION_#{k}"
    end
    "v" + v.join(".")
  end

  def build(image)
    Dir.mktmpdir("cacrt") do |dir|
      fetch_from_image(image, dir)
      cmake = File.read(File.join(dir, "CMakeLists.txt"))
      full_block = cmake[/if\(CONFIG_MBEDTLS_CERTIFICATE_BUNDLE_DEFAULT_FULL\)\n(.*?)\n\s*elseif/m, 1]
      unless full_block && full_block.strip == FULL_LINE
        raise Error, "IDF's full bundle is no longer cacrt_all.pem + cacrt_local.pem " \
                     "(components/mbedtls/CMakeLists.txt); this tool needs updating"
      end
      version = idf_version(File.read(File.join(dir, "esp_idf_version.h")))
      sources = []
      entries = []
      mozilla = nil
      INPUTS.each do |f|
        text = File.binread(File.join(dir, f)).force_encoding("UTF-8")
        sources << [f, Digest::SHA256.hexdigest(text)]
        mozilla ||= mozilla_date(text)
        entries.concat(parse_pem(text))
      end
      names = read_exclude(File.read(EXCLUDE_FILE))
      kept = exclude(entries, names)
      text = render(entries: kept, idf_version: version, sources: sources,
                    source_count: entries.size, excluded: names, mozilla: mozilla)
      File.binwrite(OUTPUT_FILE, text)
      puts "IDF #{version}: #{entries.size} certificates, #{names.size} excluded, " \
           "#{kept.size} written to config/cacrt_fmrb.pem"
      sources.each { |f, sha| puts "  #{f} sha256 #{sha}" }
      puts "  cacrt_fmrb.pem sha256 #{Digest::SHA256.hexdigest(text)}"
    end
  end

  # Subject names (DER) of a binary bundle made by IDF's gen_crt_bundle.py:
  # a table of u32 offsets, then per certificate u16 name_len, u16 key_len,
  # the subject DER and the public key DER.
  def bin_subjects(bin)
    first = bin.unpack1("L<")
    count = first / 4
    offsets = bin.unpack("L<#{count}")
    offsets.map do |off|
      name_len, _key_len = bin.byteslice(off, 4).unpack("S<S<")
      bin.byteslice(off + 4, name_len)
    end
  end

  def check_bin(path)
    pem = File.read(OUTPUT_FILE)
    certs = parse_pem(pem).map { |e| OpenSSL::X509::Certificate.new(e.pem) }
    want = certs.map { |c| c.subject.to_der }.sort
    got = bin_subjects(File.binread(path)).sort
    excluded = read_exclude(File.read(EXCLUDE_FILE))
    hits = got.map { |d| OpenSSL::X509::Name.new(d).to_s(OpenSSL::X509::Name::RFC2253) }
              .select { |s| excluded.any? { |n| s.include?("CN=#{n}") } }
    puts "#{path}: #{got.size} certificates (config/cacrt_fmrb.pem: #{want.size})"
    raise Error, "excluded certificates in the build's bundle: #{hits.join('; ')}" unless hits.empty?
    raise Error, "the build's bundle differs from config/cacrt_fmrb.pem" unless got == want
    puts "  same subjects as config/cacrt_fmrb.pem; none of the excluded names"
  end
end

if $PROGRAM_NAME == __FILE__
  image = nil
  bin = nil
  OptionParser.new do |o|
    o.banner = "usage: cacrt_bundle.rb --image <build image> | --check-bin <x509_crt_bundle>"
    o.on("--image IMAGE", "the ESP-IDF build image to read the bundle from") { |v| image = v }
    o.on("--check-bin PATH", "compare an IDF-built x509_crt_bundle with the PEM") { |v| bin = v }
  end.parse!
  begin
    if bin
      CacrtBundle.check_bin(bin)
    elsif image
      CacrtBundle.build(image)
    else
      abort "cacrt_bundle.rb: --image or --check-bin is needed"
    end
  rescue CacrtBundle::Error => e
    abort "cacrt_bundle.rb: #{e.message}"
  end
end
