def parse_art(art):
    """Turn one art string into eight row bytes (bit 7 = leftmost pixel)."""
    rows = art.split()
    if len(rows) != 8:
        raise ValueError("glyph needs 8 rows, got %d: %r" % (len(rows), art))
    out = []
    for row in rows:
        if len(row) != 8:
            raise ValueError("row needs 8 columns: %r" % row)
        value = 0
        for bit, ch in enumerate(row):
            if ch == '#':
                value |= 0x80 >> bit
            elif ch != '.':
                raise ValueError("row uses '#' and '.' only: %r" % row)
        out.append(value)
    return out


def bg_pattern(code):
    """Placeholder artwork for the background pattern codes (184-255).

    The real set is drawn in B3 together with the tile sheet; until then each
    code gets a distinguishable geometric pattern so a screen full of them is
    still readable on a screenshot.
    """
    kind = (code - 0xB8) % 8
    rows = []
    for y in range(8):
        if kind == 0:
            v = 0xFF if y % 2 == 0 else 0x00           # horizontal stripes
        elif kind == 1:
            v = 0xAA                                    # vertical stripes
        elif kind == 2:
            v = 0xFF if y in (0, 7) else 0x81           # frame
        elif kind == 3:
            v = 0xFF                                    # solid
        elif kind == 4:
            v = 0x18 if 2 <= y <= 5 else 0x00           # centre block
        elif kind == 5:
            v = (0xCC if y % 4 < 2 else 0x33)           # checker
        elif kind == 6:
            v = 0x01 << (y % 8)                         # diagonal
        else:
            v = 0x00 if y < 4 else 0xFF                 # half tone
        rows.append(v)
    return rows


def build():
    glyphs = [[0] * 8 for _ in range(256)]

    for table in (ASCII_ART, KANA_ART, SYMBOL_ART):
        for code, art in table.items():
            glyphs[code] = parse_art(art)

    # Voiced marks: two strokes in the top right corner, a small square for
    # handakuten. Both areas are free in every base kana glyph.
    for code, base in DAKUTEN.items():
        rows = list(glyphs[base])
        rows[0] |= 0x02
        rows[1] |= 0x01
        glyphs[code] = rows
    for code, base in HANDAKUTEN.items():
        rows = list(glyphs[base])
        rows[0] |= 0x03
        rows[1] |= 0x03
        glyphs[code] = rows

    for code in range(0xB8, 0x100):
        glyphs[code] = bg_pattern(code)

    # 0-31 are the BG graphic groups the system reserves (core_spec sec 12):
    # leave them blank until B3 defines the tile set.
    return glyphs


def emit_c(glyphs, path):
    lines = []
    lines.append("// Generated by tools/gen_basic_font.py -- do not edit by hand.")
    lines.append("//")
    lines.append("// FMRuby BASIC 8x8 text font. Code positions follow the Family BASIC")
    lines.append("// character table (core_spec sec 12); the shapes are original artwork for")
    lines.append("// this project. Bit 7 of each byte is the leftmost pixel.")
    lines.append("")
    lines.append('#include "basic_font8.h"')
    lines.append("")
    lines.append("const uint8_t basic_font8[256][8] = {")
    for code in range(256):
        rows = ", ".join("0x%02X" % v for v in glyphs[code])
        lines.append("    {%s},  // %d" % (rows, code))
    lines.append("};")
    lines.append("")
    with open(path, "w") as fp:
        fp.write("\n".join(lines))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default = os.path.join(here, "..", "components", "basic", "assets", "basic_font8.c")
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.normpath(default)
    glyphs = build()
    emit_c(glyphs, out)
    print("wrote %s" % out)


if __name__ == "__main__":
    main()
