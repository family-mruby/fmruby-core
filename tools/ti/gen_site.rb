  # A signature longer than this is written one parameter to a line.
  WRAP = 72

  ClassPage = Struct.new(:name, :file, :summary, :long, :comment, :constants, :aliases, :singletons, :instances,
                         :supers, keyword_init: true)
  Entry = Struct.new(:name, :signatures, :summary, :long, keyword_init: true)

  module_function

  def area_of(sig_file)
    base = File.basename(sig_file, ".rbs")
    found = AREAS.find { |_, _, files| files.include?(base) }
    found ? found[0, 2] : OTHER
  end

  # One language of a summary line ("日本語 <<en>> English"). A line without
  # the marker is the same for both readers.
  def pick_summary(line, lang)
    i = line.index(LANG_MARK)
    return line.strip if i.nil?
    (lang == "en" ? line[(i + LANG_MARK.length)..].to_s : line[0, i].to_s).strip
  end

  # One language of a long form: the two halves sit on either side of a line
  # that is nothing but the marker.
  def pick_long(text, lang)
    return "" if text.nil?
    lines = text.lines
    mark = lines.index { |l| l.strip == LANG_MARK }
    half = mark.nil? ? text : (lang == "en" ? lines[(mark + 1)..] : lines[0, mark]).join
    join_wide_lines(half.strip)
  end

  # Markdown turns a line break inside a paragraph into a space, which a
  # browser shows between two Japanese characters ("呼べる。 メソッド"). The
  # sig comments are wrapped at 39 columns for the editor, so join the lines of
  # a paragraph where both sides of the break are wide characters. Code blocks,
  # and lines that open a list, heading, table or quote, are left alone.
  def join_wide_lines(text)
    out = []
    fence = false
    text.each_line(chomp: true) do |line|
      if line.lstrip.start_with?("```")
        fence = !fence
        out << line
        next
      end
      prev = out.last
      if !fence && prev && !prev.lstrip.start_with?("```") && prev.match?(/[^\x00-\x7F]\z/) &&
         line.match?(/\A[^\x00-\x7F]/) && !line.match?(/\A\s*([-*+>|#]|\d+\.)\s/)
        out[-1] = prev + line
      else
        out << line
      end
    end
    out.join("\n")
  end

  def comment_parts(comment)
    lines = comment&.string.to_s.lines
    [lines.first.to_s.strip, (lines[1..] || []).join.strip]
  end

  def collect(sig_dir)
    pages = {}
    Dir[File.join(sig_dir, "*.rbs")].sort.each do |path|
      declarations = RBS::Parser.parse_signature(File.read(path)).last
      TiHelp.each_class(declarations) do |class_name, declaration|
        page = pages[class_name] ||= ClassPage.new(name: class_name, file: path, summary: "", long: "", comment: "",
                                                   constants: [], aliases: [], singletons: [],
                                                   instances: [], supers: [])
        summary, long = comment_parts(declaration.comment)
        if !summary.empty? && page.summary.empty?
          page.summary = summary
          page.long = long
          page.comment = declaration.comment.string.to_s
          page.file = path
        end
        if declaration.is_a?(RBS::AST::Declarations::Class) && declaration.super_class
          page.supers << declaration.super_class.name.to_s.sub(/\A::/, "")
        end
        declaration.members.each do |member|
          case member
          when RBS::AST::Declarations::Constant
            s, l = comment_parts(member.comment)
            page.constants << Entry.new(name: member.name.to_s, signatures: [member.type.to_s], summary: s, long: l)
          when RBS::AST::Declarations::TypeAlias
            s, l = comment_parts(member.comment)
            page.aliases << Entry.new(name: member.name.to_s, signatures: [member.type.to_s], summary: s, long: l)
          when RBS::AST::Members::MethodDefinition
            s, l = comment_parts(member.comment)
            sigs = member.overloads.map { |o| [member.name.to_s, o.method_type.to_s] }
            entry = Entry.new(name: member.name.to_s, signatures: sigs, summary: s, long: l)
            (member.singleton? ? page.singletons : page.instances) << entry
          end
        end
      end
    end
    pages
  end

  # --- what is left out ----------------------------------------------------

  # site_exclude.yml: {"classes" => {"Name" => "reason", "Outer::*" => "reason"}}.
  # "Outer::*" leaves out every class inside Outer (not Outer itself).
  def load_exclude(path)
    return {} if path.nil? || !File.exist?(path)
    data = YAML.safe_load(File.read(path)) || {}
    classes = data["classes"] || {}
    raise "#{path}: 'classes' must be a mapping of class name to reason" unless classes.is_a?(Hash)
    classes.each do |name, reason|
      raise "#{path}: #{name} has no reason" if reason.to_s.strip.empty?
    end
    classes
  end

  def excluded?(name, rules)
    rules.each_key do |rule|
      if rule.end_with?("::*")
        return true if name.start_with?(rule.delete_suffix("*"))
      elsif rule == name
        return true
      end
    end
    false
  end

  # --- names and links -----------------------------------------------------

  def slug(class_name) = class_name.gsub("::", "__")

  # A name as written inside a class means the innermost class of that name:
  # "Label" inside FmrbUI::Button is FmrbUI::Button::Label, then FmrbUI::Label,
  # then Label.
  def resolve(name, context, known)
    name = name.delete_prefix("::")
    parts = context.split("::")
    parts.size.downto(0) do |n|
      full = (parts[0, n] + [name]).join("::")
      return full if known.include?(full)
    end
    nil
  end

  def html_escape(text) = text.to_s.gsub("&", "&amp;").gsub("<", "&lt;").gsub(">", "&gt;")

  # The href from one class page to another, as the built site has them:
  # api/reference/A/ next to api/reference/B/ with directory URLs (the
  # default), A.html next to B.html without.
  def class_href(name, directory_urls)
    directory_urls ? "../#{slug(name)}/" : "#{slug(name)}.html"
  end

  CLASS_NAME = /(?<![\w:])(?:::)?[A-Z]\w*(?:::[A-Z]\w*)*/

  # Escape a piece of a signature and link the classes in it that have a page
  # (not the page's own class).
  def linkify(text, page_name, known, directory_urls)
    out = +""
    rest = text
    while (m = CLASS_NAME.match(rest))
      out << html_escape(m.pre_match)
      full = resolve(m[0], page_name, known)
      out << if full && full != page_name
               %(<a href="#{class_href(full, directory_urls)}">#{html_escape(m[0])}</a>)
             else
               html_escape(m[0])
             end
      rest = m.post_match
    end
    out << html_escape(rest)
  end

  # Split at the commas that are not inside (), [], {}.
  def top_split(text)
    parts = []
    depth = 0
    cur = +""
    text.each_char do |ch|
      case ch
      when "(", "[", "{" then depth += 1
      when ")", "]", "}" then depth -= 1
      end
      if ch == "," && depth.zero?
        parts << cur.strip
        cur = +""
      else
        cur << ch
      end
    end
    parts << cur.strip unless cur.strip.empty?
    parts
  end

  # One overload as lines of text: as it is when short, else the parameters
  # one to a line between the name and the result.
  def signature_lines(name, method_type)
    one = "#{name}#{method_type}"
    return [one] if one.length <= WRAP
    head = method_type[/\A\[[^\]]*\]\s*/].to_s
    body = method_type[head.length..]
    return [one] unless body.start_with?("(")
    depth = 0
    close = body.each_char.with_index.find do |ch, _|
      depth += 1 if ch == "("
      depth -= 1 if ch == ")"
      depth.zero?
    end&.last
    return [one] if close.nil?
    params = top_split(body[1...close])
    return [one] if params.size < 2
    ["#{name}#{head}("] + params.each_with_index.map { |p, i| "  #{p}#{i < params.size - 1 ? ',' : ''}" } +
      [")#{body[(close + 1)..]}"]
  end

  # The signatures of a method as a code block in HTML, so the class names in
  # it can be links (a Markdown code block cannot hold one). Every overload is
  # shown; a blank line between them when one is wrapped.
  def signature_block(page, entry, known, directory_urls)
    blocks = entry.signatures.map do |name, method_type|
      lines = signature_lines(name, method_type)
      # The method's own name is never a class, even when it starts with a
      # capital (Kernel#Integer).
      lines.each_with_index.map do |line, i|
        if i.zero?
          html_escape(name) + linkify(line[name.length..], page.name, known, directory_urls)
        else
          linkify(line, page.name, known, directory_urls)
        end
      end.join("\n")
    end
    sep = blocks.any? { |b| b.include?("\n") } ? "\n\n" : "\n"
    %(<pre class="fmrb-sig"><code>#{blocks.join(sep)}</code></pre>\n\n)
  end

  # A class name as Markdown: a link to its page when it has one.
  def class_link(name, known, page_name = nil)
    full = page_name ? resolve(name, page_name, known) : (known.include?(name) ? name : nil)
    full && full != page_name ? "[`#{name}`](#{slug(full)}.md)" : "`#{name}`"
  end

