  # A table cell: no line breaks, no bare pipes.
  def cell(text) = text.to_s.gsub("|", "\\|").gsub("\n", " ")

  # The name column of a table. A narrow column breaks a code span anywhere
  # (composite_re|gion); the site's stylesheet keeps this class on one line.
  # The Markdown inside the span is still Markdown, so a link stays a link.
  def name_cell(markdown) = %(<span class="fmrb-name">#{markdown}</span>)

  # The guides a class page points at: its own, else its outer class's.
  def guides_for(name)
    parts = name.split("::")
    parts.size.downto(1) do |n|
      outer = parts[0, n].join("::")
      found = GUIDES.select { |_, _, _, classes| classes.include?(outer) }
      return found unless found.empty?
    end
    []
  end

  def method_section(page, entry, sep, lang, ctx)
    t = T[lang]
    out = +"### #{page.name}#{sep}#{entry.name}\n\n"
    out << signature_block(page, entry, ctx[:known], ctx[:directory_urls])
    summary = pick_summary(entry.summary, lang)
    out << "#{summary.empty? ? t[:none] : summary}\n\n"
    long = pick_long(entry.long, lang)
    out << "#{long}\n\n" unless long.empty?
    out
  end

  def render(page, lang, ctx)
    t = T[lang]
    known = ctx[:known]
    out = +"# #{page.name}\n\n"
    lead, rest = class_intro(page, lang).split(/\n[ \t]*\n/, 2)
    out << "#{lead}\n\n" unless lead.to_s.empty?
    guides = guides_for(page.name)
    unless guides.empty?
      links = guides.map { |file, en, ja, _| "[#{lang == 'en' ? en : ja}](../#{file}.md)" }
      out << "#{t[:guide].call(links.join(lang == 'en' ? ', ' : '、'))}\n\n"
    end
    unless page.supers.empty?
      out << "#{t[:inherits]}: #{page.supers.uniq.map { |s| class_link(s, known, page.name) }.join(', ')}\n\n"
    end
    out << "#{rest.strip}\n\n" unless rest.to_s.strip.empty?

    unless page.constants.empty?
      out << "## #{t[:constants]}\n\n| #{t[:name]} | #{t[:type]} | #{t[:what]} |\n|---|---|---|\n"
      page.constants.each do |c|
        type = c.signatures.first
        type_cell = resolve(type, page.name, known) ? class_link(type, known, page.name) : "`#{cell(type)}`"
        out << "| #{name_cell("`#{c.name}`")} | #{type_cell} | #{cell(pick_summary(c.summary, lang))} |\n"
      end
      out << "\n"
    end
    unless page.aliases.empty?
      out << "## #{t[:aliases]}\n\n| #{t[:name]} | #{t[:type]} | #{t[:what]} |\n|---|---|---|\n"
      page.aliases.each do |a|
        out << "| #{name_cell("`#{a.name}`")} | `#{cell(a.signatures.first)}` | #{cell(pick_summary(a.summary, lang))} |\n"
      end
      out << "\n"
    end
    unless page.singletons.empty?
      out << "## #{t[:singletons]}\n\n"
      page.singletons.each { |e| out << method_section(page, e, ".", lang, ctx) }
    end
    unless page.instances.empty?
      out << "## #{t[:instances]}\n\n"
      page.instances.each { |e| out << method_section(page, e, "#", lang, ctx) }
    end
    out << "---\n\n*#{t[:generated].call(ctx[:version])}*\n"
    out
  end

  def grouped(pages)
    groups = {}
    pages.each_value do |page|
      (groups[area_of(page.file)] ||= []) << page
    end
    order = AREAS.map { |en, ja, _| [en, ja] } + [OTHER]
    groups.sort_by { |key, _| [order.index(key) || order.size, key[0]] }
          .map { |key, list| [key, list.sort_by(&:name)] }
  end

  # A class comment in one language. Three shapes are in sig/: the summary
  # line in both languages ("日本語 <<en>> English") over a long form that may
  # have two halves; a first line in Japanese only, over two halves (the
  # English half then opens with its own summary); and one language
  # throughout, where the first line is often just the first line of a
  # wrapped sentence.
  def class_intro(page, lang)
    lines = page.comment.to_s.lines
    return "" if lines.empty?
    first = lines[0]
    rest = lines[1..]
    mark = rest.index { |l| l.strip == LANG_MARK }
    half = mark.nil? ? rest : (lang == "en" ? rest[(mark + 1)..] : rest[0, mark])
    text = if first.include?(LANG_MARK)
             "#{pick_summary(first, lang)}\n\n#{half.join}"
           elsif mark && lang == "en"
             half.join
           else
             first + half.join
           end
    join_wide_lines(text.strip)
  end

  # The line the index shows for a class: the first sentence of its comment.
  def index_summary(page, lang)
    para = class_intro(page, lang).split(/\n[ \t]*\n/).first.to_s
    return "" if para.lstrip.start_with?("```")
    para = para.gsub(/\s*\n\s*/, " ").strip
    sentence = para[/\A.*?(?:。|[.!?](?=\s|\z))/] || para
    sentence = sentence.delete("*") if sentence.scan("**").size.odd?
    sentence = sentence.delete("`") if sentence.count("`").odd?
    sentence
  end

  def render_index(groups, lang, version)
    t = T[lang]
    out = +"# #{t[:index_title]}\n\n"
    out << "!!! note \"#{t[:notice_title]}\"\n    #{t[:notice].call(version)}\n\n"
    out << "#{t[:index_lead]}\n\n"
    groups.each do |(en, ja), list|
      out << "## #{lang == 'en' ? en : ja}\n\n| #{t[:klass]} | #{t[:what]} | #{t[:methods]} |\n|---|---|---|\n"
      list.each do |page|
        count = page.singletons.size + page.instances.size
        out << "| #{name_cell("[`#{page.name}`](#{slug(page.name)}.md)")} | #{cell(index_summary(page, lang))} | #{count} |\n"
      end
      out << "\n"
    end
    out << "---\n\n*#{t[:generated].call(version)}*\n"
    out
  end

  # --- mkdocs.yml ----------------------------------------------------------

  def nav_lines(groups)
    lines = [NAV_BEGIN, "      - Class Reference:", "          - Overview: api/reference/index.md"]
    groups.each do |(en, _), list|
      lines << "          - #{en}:"
      list.each { |page| lines << "              - \"#{page.name}\": api/reference/#{slug(page.name)}.md" }
    end
    lines << NAV_END
    lines
  end

  # Replace what is between two marker lines; the first time, insert the
  # block after the last line of the entry that `anchor` finds, i.e. the last
  # following line indented by at least `indent`.
  def splice(lines, first, last, block, anchor, indent, what)
    b = lines.index(first)
    e = lines.index(last)
    if b && e && e > b
      lines[b..e] = block
      return lines
    end
    start = lines.index { |l| l.match?(anchor) } or raise "mkdocs.yml: no #{what}"
    tail = start
    ((start + 1)...lines.size).each do |i|
      break unless lines[i].start_with?(" " * indent) || lines[i].strip.empty?
      tail = i unless lines[i].strip.empty?
    end
    lines.insert(tail + 1, *block)
    lines
  end

  # The Japanese names of the nav entries this tool adds, in the ja language's
  # nav_translations. A name the site already translates is left to it.
  def translation_lines(lines, groups, warn_io)
    b = lines.index(TR_BEGIN)
    e = lines.index(TR_END)
    outside = b && e && e > b ? lines[0...b] + lines[(e + 1)..] : lines
    have = {}
    outside.each do |l|
      m = l.match(/\A {12}([^#\s][^:]*):\s*(.+?)\s*\z/) or next
      have[m[1]] = m[2]
    end
    wanted = [["Class Reference", "クラスリファレンス"]] + groups.map(&:first)
    block = [TR_BEGIN]
    wanted.uniq.each do |en, ja|
      if have.key?(en)
        warn_io.puts "gen_site: mkdocs.yml translates #{en} as #{have[en]}, the index says #{ja}" if have[en] != ja
        next
      end
      block << "            #{en}: #{ja}"
    end
    block << TR_END
    block
  end

  def update_mkdocs(mkdocs_path, groups, warn_io)
    lines = File.read(mkdocs_path).lines(chomp: true)
    lines = splice(lines, NAV_BEGIN, NAV_END, nav_lines(groups), /\A  - API Reference:\s*\z/, 6,
                   "'  - API Reference:' entry in nav")
    lines = splice(lines, TR_BEGIN, TR_END, translation_lines(lines, groups, warn_io),
                   /\A {10}nav_translations:\s*\z/, 12, "nav_translations of a language")
    write_if_changed(mkdocs_path, lines.join("\n") + "\n")
  end

  def directory_urls?(mkdocs_path)
    File.read(mkdocs_path).match(/^use_directory_urls:\s*(\S+)/)&.[](1) != "false"
  end

  # --- the guides written by hand ------------------------------------------

  # The line at the end of a guide that names its classes, between two marker
  # comments. The rest of the page is never touched; with no class to name,
  # the block goes away.
  def update_guide(path, line)
    return false unless File.exist?(path)
    text = File.read(path)
    b = text.index(GUIDE_BEGIN)
    e = text.index(GUIDE_END)
    if b && e && e > b
      head = text[0...b].sub(/\n+\z/, "\n")
      tail = text[(e + GUIDE_END.length)..].sub(/\A\n/, "")
    else
      head = text.sub(/\n*\z/, "\n")
      tail = ""
    end
    block = line ? "\n#{GUIDE_BEGIN}\n#{line}\n#{GUIDE_END}\n" : ""
    write_if_changed(path, head + block + tail)
    true
  end

  def guide_line(classes, lang, known, all)
    t = T[lang]
    links = if all
              ["[#{t[:guide_all]}](reference/index.md)"]
            else
              classes.select { |c| known.include?(c) }.map { |c| "[`#{c}`](reference/#{slug(c)}.md)" }
            end
    return nil if links.empty?
    "**#{t[:guide_line]}:** #{links.join(lang == 'en' ? ', ' : '、')}"
  end

  # --- writing -------------------------------------------------------------

  def write_if_changed(path, text)
    return false if File.exist?(path) && File.read(path) == text
    File.write(path, text)
    true
  end

  Result = Struct.new(:classes, :areas, :written, :removed, :excluded, :others, keyword_init: true)

  def generate(sig_dir:, site_dir:, only: nil, version: nil, exclude_path: nil, warn_io: $stderr)
    pages = collect(sig_dir)
    rules = load_exclude(exclude_path)
    excluded = pages.keys.select { |name| excluded?(name, rules) }
    pages.reject! { |name, _| excluded.include?(name) }
    pages.select! { |name, _| only.include?(name) } if only
    raise "no classes to write" if pages.empty?

    others = pages.values.map(&:file).uniq.select { |f| area_of(f) == OTHER }.sort
    others.each do |f|
      warn_io.puts "gen_site: #{File.basename(f)} is in no area of TiSite::AREAS; its classes are listed under Other"
    end

    mkdocs = File.join(site_dir, "mkdocs.yml")
    ctx = { known: pages.keys.to_set, version: version, directory_urls: directory_urls?(mkdocs) }
    out_dir = File.join(site_dir, "docs", "api", "reference")
    FileUtils.mkdir_p(out_dir)
    groups = grouped(pages)

    files = {}
    pages.each_value do |page|
      files["#{slug(page.name)}.md"] = render(page, "en", ctx)
      files["#{slug(page.name)}.ja.md"] = render(page, "ja", ctx)
    end
    files["index.md"] = render_index(groups, "en", version)
    files["index.ja.md"] = render_index(groups, "ja", version)

    written = files.count { |name, text| write_if_changed(File.join(out_dir, name), text) }

    # Remove what this tool wrote last time and did not write now; nothing
    # else in the directory is touched.
    list_path = File.join(out_dir, LIST_FILE)
    before = File.exist?(list_path) ? File.read(list_path).lines(chomp: true) : []
    removed = (before - files.keys).select { |name| name.match?(/\A[\w.-]+\z/) && !name.start_with?(".") }
    removed.each { |name| FileUtils.rm_f(File.join(out_dir, name)) }
    write_if_changed(list_path, files.keys.sort.join("\n") + "\n")

    update_mkdocs(mkdocs, groups, warn_io)
    GUIDES.each do |file, _, _, classes|
      %w[en ja].each do |lang|
        path = File.join(site_dir, "docs", "api", lang == "en" ? "#{file}.md" : "#{file}.#{lang}.md")
        line = guide_line(classes, lang, ctx[:known], classes.empty?)
        warn_io.puts "gen_site: no guide page #{path}" unless update_guide(path, line)
      end
    end

    Result.new(classes: pages.size, areas: groups.size, written: written, removed: removed,
               excluded: excluded.sort, others: others.map { |f| File.basename(f) })
  end
end

