#!/usr/bin/env ruby
# frozen_string_literal: true
#
# Turn sig/*.rbs into the class reference of the documentation site
# (family-mruby.github.io): one page per class and language, an index, and the
# navigation entries (doc/sig_coverage S7).
#
# The site's API pages written by hand are guides by topic (how the parts fit,
# pictures, tables). These pages are the other half: every class with every
# method, constant, signature and example the signatures carry, so a guide
# that falls behind still has something exact to point at.
#
#   <site>/docs/api/reference/index.md, index.ja.md   the classes by area
#   <site>/docs/api/reference/<Class>.md              English (the site's default)
#   <site>/docs/api/reference/<Class>.ja.md           Japanese
#   <site>/docs/api/reference/.generated              the files written last time
#   <site>/docs/api/<guide>.md, .ja.md                one line between two marker
#                                                     comments at the end
#   <site>/mkdocs.yml                                 the nav and the Japanese
#                                                     names, between marker lines
#
# The same doc comments make the editor's F1 pages (gen_help.rb); what differs
# is the shape. A page here is read in a browser: constants in a table, one
# heading per method so it can be linked to, the signature as code with the
# classes in it linked, every overload shown.
#
# Only what this tool wrote is ever replaced or removed: the pages listed in
# .generated, and the text between its own marker lines. Running it twice on
# the same sig/ changes nothing.
#
# usage: gen_site.rb --sig-dir sig --site ../family-mruby.github.io
#                    [--exclude tools/ti/site_exclude.yml] [--only A,B] [--version TEXT]

