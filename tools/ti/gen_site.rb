#!/usr/bin/env ruby
# frozen_string_literal: true
#
# Turn sig/*.rbs into the class reference of the documentation site
# (family-mruby.github.io): one page per class and language, an index, and the
# navigation entries (doc/sig_coverage S7).
#
# The site's API pages written by hand are guides by topic (how the parts fit,
# pictures, tables). These pages are the other half: every class with every
# method, constant, signature and example the signatures carry, so a guide
# that falls behind still has something exact to point at.
#
#   <site>/docs/api/reference/index.md, index.ja.md   the classes by area
#   <site>/docs/api/reference/<Class>.md              English (the site's default)
#   <site>/docs/api/reference/<Class>.ja.md           Japanese
#   <site>/mkdocs.yml                                 the nav between two marker lines
#
# The same doc comments make the editor's F1 pages (gen_help.rb); what differs
# is the shape. A page here is read in a browser: constants in a table, one
# heading per method so it can be linked to, the signature as code, every
# overload shown.
#
# usage: gen_site.rb --sig-dir sig --site ../family-mruby.github.io [--only A,B] [--version TEXT]

require "optparse"
require "fileutils"
require "rbs"
require_relative "gen_help"

module TiSite
  LANG_MARK = TiHelp::LANG_MARK
  NAV_BEGIN = "      # BEGIN class reference (generated by fmruby-core tools/ti/gen_site.rb; do not edit)"
  NAV_END = "      # END class reference"

  # sig file (without .rbs) => the area its classes are listed under.
  # A file not named here goes under "Ruby core" when it is one of the classes
  # of the language, else under its own name.
  AREAS = [
    ["Application", "アプリ", %w[fmrb_app fmrb_system fmrb_const fmrb_misc fmrb_types fmrb_assoc fmrb_lib]],
    ["Drawing", "描画", %w[fmrb_gfx fmrb_sprite fmrb_tile fmrb_p5 fmrb_picture fmrb_ui fmrb_raycast]],
    ["Sound", "音", %w[fmrb_audio fmrb_midi fmrb_fft]],
    ["Files and time", "ファイルと時刻", %w[fmrb_file dir io time]],
    ["Data", "データ", %w[json message_pack digest]],
    ["Network", "ネットワーク", %w[fmrb_asterism fmrb_table_client asterism_ros fmrb_net]],
    ["Machine and devices", "本体と機器", %w[machine gc rng math fmrb_hw i2c gpio]],
    ["Ruby core", "Ruby の基本クラス",
     %w[object kernel class enumerable string symbol integer float array hash range proc
        nil_class true_class false_class untyped]],
  ].freeze

  ClassPage = Struct.new(:name, :file, :summary, :long, :constants, :singletons, :instances, :supers,
                         keyword_init: true)
  Entry = Struct.new(:name, :signatures, :summary, :long, keyword_init: true)

  module_function

  def area_of(sig_file)
    base = File.basename(sig_file, ".rbs")
    AREAS.find { |_, _, files| files.include?(base) } || [base, base, [base]]
  end

  # One language of a summary line ("日本語 <<en>> English"). A line without
  # the marker is the same for both readers.
  def pick_summary(line, lang)
    i = line.index(LANG_MARK)
    return line.strip if i.nil?
    (lang == "en" ? line[(i + LANG_MARK.length)..].to_s : line[0, i].to_s).strip
  end

  # One language of a long form: the two halves sit on either side of a line
  # that is nothing but the marker.
  def pick_long(text, lang)
    return "" if text.nil?
    lines = text.lines
    mark = lines.index { |l| l.strip == LANG_MARK }
    return text.strip if mark.nil?
    (lang == "en" ? lines[(mark + 1)..] : lines[0, mark]).join.strip
  end

  def comment_parts(comment)
    lines = comment&.string.to_s.lines
    [lines.first.to_s.strip, (lines[1..] || []).join.strip]
  end

  def collect(sig_dir)
    pages = {}
    Dir[File.join(sig_dir, "*.rbs")].sort.each do |path|
      declarations = RBS::Parser.parse_signature(File.read(path)).last
      TiHelp.each_class(declarations) do |class_name, declaration|
        page = pages[class_name] ||= ClassPage.new(name: class_name, file: path, summary: "", long: "",
                                                   constants: [], singletons: [], instances: [], supers: [])
        summary, long = comment_parts(declaration.comment)
        if !summary.empty? && page.summary.empty?
          page.summary = summary
          page.long = long
          page.file = path
        end
        if declaration.is_a?(RBS::AST::Declarations::Class) && declaration.super_class
          page.supers << declaration.super_class.name.to_s.sub(/\A::/, "")
        end
        declaration.members.each do |member|
          case member
          when RBS::AST::Declarations::Constant
            s, l = comment_parts(member.comment)
            page.constants << Entry.new(name: member.name.to_s, signatures: [member.type.to_s], summary: s, long: l)
          when RBS::AST::Members::MethodDefinition
            s, l = comment_parts(member.comment)
            sigs = member.overloads.map { |o| "#{member.name}#{o.method_type}" }
            entry = Entry.new(name: member.name.to_s, signatures: sigs, summary: s, long: l)
            (member.singleton? ? page.singletons : page.instances) << entry
          end
        end
      end
    end
    pages
  end

  def slug(class_name) = class_name.gsub("::", "__")

  T = {
    "en" => { constants: "Constants", singletons: "Class methods", instances: "Instance methods",
              name: "Name", type: "Type", what: "What it is", inherits: "Inherits from",
              generated: "This page is generated from the API signatures of Family mruby (`sig/`)",
              index_title: "Class reference", index_lead:
                "Every class an app can use, with every method, constant and example the API " \
                "signatures carry. The pages are generated; the guides by topic are under " \
                "[API Reference](../index.md).",
              klass: "Class / module", methods: "Methods", none: "(no description yet)" },
    "ja" => { constants: "定数", singletons: "クラスメソッド", instances: "インスタンスメソッド",
              name: "名前", type: "型", what: "中身", inherits: "継承元",
              generated: "このページは Family mruby の API の型定義 (`sig/`) から自動で作っています",
              index_title: "クラスリファレンス", index_lead:
                "アプリから使えるクラスの、すべてのメソッド・定数・例を、API の型定義から自動で作った" \
                "ページです。使い方の流れは [API リファレンス](../index.md) の各ページにあります。",
              klass: "クラス / モジュール", methods: "メソッド数", none: "(説明はまだありません)" },
  }.freeze

  # A table cell: no line breaks, no bare pipes.
  def cell(text) = text.to_s.gsub("|", "\\|").gsub("\n", " ")

  def method_section(page, entry, sep, lang)
    t = T[lang]
    out = +"### #{page.name}#{sep}#{entry.name}\n\n"
    out << "```ruby\n#{entry.signatures.join("\n")}\n```\n\n"
    summary = pick_summary(entry.summary, lang)
    out << "#{summary.empty? ? t[:none] : summary}\n\n"
    long = pick_long(entry.long, lang)
    out << "#{long}\n\n" unless long.empty?
    out
  end

  def render(page, lang, version)
    t = T[lang]
    out = +"# #{page.name}\n\n"
    # A class comment often has its first line in Japanese only and both
    # languages below it; the English half then opens with its own summary.
    two_halves = page.long.lines.any? { |l| l.strip == LANG_MARK }
    summary = pick_summary(page.summary, lang)
    summary = "" if lang == "en" && two_halves && !page.summary.include?(LANG_MARK)
    out << "#{summary}\n\n" unless summary.empty?
    out << "#{t[:inherits]}: `#{page.supers.uniq.join('`, `')}`\n\n" unless page.supers.empty?
    long = pick_long(page.long, lang)
    out << "#{long}\n\n" unless long.empty?

    unless page.constants.empty?
      out << "## #{t[:constants]}\n\n| #{t[:name]} | #{t[:type]} | #{t[:what]} |\n|---|---|---|\n"
      page.constants.each do |c|
        out << "| `#{c.name}` | `#{cell(c.signatures.first)}` | #{cell(pick_summary(c.summary, lang))} |\n"
      end
      out << "\n"
    end
    unless page.singletons.empty?
      out << "## #{t[:singletons]}\n\n"
      page.singletons.each { |e| out << method_section(page, e, ".", lang) }
    end
    unless page.instances.empty?
      out << "## #{t[:instances]}\n\n"
      page.instances.each { |e| out << method_section(page, e, "#", lang) }
    end
    out << "---\n\n*#{t[:generated]}#{version ? " (#{version})" : ''}.*\n"
    out
  end

  def grouped(pages)
    groups = {}
    pages.each_value do |page|
      en, ja, = area_of(page.file)
      (groups[[en, ja]] ||= []) << page
    end
    order = AREAS.map { |en, ja, _| [en, ja] }
    groups.sort_by { |key, _| [order.index(key) || order.size, key[0]] }
          .map { |key, list| [key, list.sort_by(&:name)] }
  end

  # The line the index shows for a class: its summary in that language, or,
  # for a Japanese-only first line, the first line of the English half.
  def index_summary(page, lang)
    return pick_summary(page.summary, lang) if lang == "ja" || page.summary.include?(LANG_MARK)
    en = pick_long(page.long, "en")
    page.long.lines.any? { |l| l.strip == LANG_MARK } ? en.lines.first.to_s.strip : pick_summary(page.summary, lang)
  end

  def render_index(groups, lang, version)
    t = T[lang]
    out = +"# #{t[:index_title]}\n\n#{t[:index_lead]}\n\n"
    groups.each do |(en, ja), list|
      out << "## #{lang == 'en' ? en : ja}\n\n| #{t[:klass]} | #{t[:what]} | #{t[:methods]} |\n|---|---|---|\n"
      list.each do |page|
        count = page.singletons.size + page.instances.size
        out << "| [`#{page.name}`](#{slug(page.name)}.md) | #{cell(index_summary(page, lang))} | #{count} |\n"
      end
      out << "\n"
    end
    out << "---\n\n*#{t[:generated]}#{version ? " (#{version})" : ''}.*\n"
    out
  end

  def nav_lines(groups)
    lines = [NAV_BEGIN, "      - Class Reference:", "          - Overview: api/reference/index.md"]
    groups.each do |(en, _), list|
      lines << "          - #{en}:"
      list.each { |page| lines << "              - \"#{page.name}\": api/reference/#{slug(page.name)}.md" }
    end
    lines << NAV_END
    lines
  end

  # The nav block replaces what is between the two marker lines; the first
  # time, it goes in as the last entry of "API Reference".
  def update_nav(mkdocs_path, groups)
    lines = File.read(mkdocs_path).lines(chomp: true)
    block = nav_lines(groups)
    b = lines.index(NAV_BEGIN)
    e = lines.index(NAV_END)
    if b && e && e > b
      lines[b..e] = block
    else
      api = lines.index { |l| l.match?(/\A  - API Reference:\s*\z/) } or
        raise "#{mkdocs_path}: no '  - API Reference:' entry in nav"
      last = api
      ((api + 1)...lines.size).each do |i|
        break unless lines[i].start_with?("      ") || lines[i].strip.empty?
        last = i unless lines[i].strip.empty?
      end
      lines.insert(last + 1, *block)
    end
    File.write(mkdocs_path, lines.join("\n") + "\n")
  end

  def generate(sig_dir:, site_dir:, only: nil, version: nil)
    pages = collect(sig_dir)
    pages.select! { |name, _| only.include?(name) } if only
    raise "no classes to write" if pages.empty?

    out_dir = File.join(site_dir, "docs", "api", "reference")
    FileUtils.rm_rf(out_dir)
    FileUtils.mkdir_p(out_dir)
    groups = grouped(pages)
    pages.each_value do |page|
      File.write(File.join(out_dir, "#{slug(page.name)}.md"), render(page, "en", version))
      File.write(File.join(out_dir, "#{slug(page.name)}.ja.md"), render(page, "ja", version))
    end
    File.write(File.join(out_dir, "index.md"), render_index(groups, "en", version))
    File.write(File.join(out_dir, "index.ja.md"), render_index(groups, "ja", version))
    update_nav(File.join(site_dir, "mkdocs.yml"), groups)
    [pages.size, groups.size]
  end
end

if $PROGRAM_NAME == __FILE__
  options = { sig_dir: "sig", site: nil, only: nil, version: nil }
  OptionParser.new do |parser|
    parser.banner = "usage: gen_site.rb --sig-dir DIR --site SITE_DIR [--only A,B] [--version TEXT]"
    parser.on("--sig-dir DIR") { |v| options[:sig_dir] = v }
    parser.on("--site DIR", "a checkout of family-mruby.github.io") { |v| options[:site] = v }
    parser.on("--only LIST", "only these classes (comma separated), for a trial") { |v| options[:only] = v.split(",") }
    parser.on("--version TEXT", "what the pages say they were made from") { |v| options[:version] = v }
  end.parse!
  abort "gen_site.rb: --site is required" unless options[:site]
  abort "gen_site.rb: #{options[:site]} has no mkdocs.yml" unless File.exist?(File.join(options[:site], "mkdocs.yml"))

  classes, areas = TiSite.generate(sig_dir: options[:sig_dir], site_dir: options[:site],
                                   only: options[:only], version: options[:version])
  puts "gen_site: #{classes} classes in #{areas} areas -> #{File.join(options[:site], 'docs/api/reference')}"
end
