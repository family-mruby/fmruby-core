  def on_create
    FmrbI18n.add(STRINGS)
    @gfx.set_font(:default)
    @gfx.set_text_size(1)
    @w = @user_area_width
    @h = @user_area_height
    @crt_text = FmrbApp.crt_state
    @crt_here = @crt_text != ""
    parse_crt
    @crt_dirty = false
    @ask = FmrbApp.settings_page
    @page = ask_page(@ask)
    @wifi_text = nil
    @bt_text = nil
    @aps = []
    @devs = []
    @sel = 0
    @sel_name = nil
    @top = 0
    @pw = ""
    @msg = ""
    build_widgets
    Log.info("settings: the #{page_name(@page)} page, user area #{@w}x#{@h} at (#{@user_area_x0},#{@user_area_y0})")
    read_state(true)
    draw_page
  end

  def on_update
    ask = FmrbApp.settings_page
    if ask != @ask
      @ask = ask
      switch_page(ask_page(ask))
    end
    save_crt if @crt_dirty
    draw_page if read_state(false)
    POLL_MS
  end

  def on_event(ev)
    t = ev[:type]
    id = @ui.handle(ev)
    if id
      act(id)
      return
    end
    if t == :mouse_down && ev[:button] == 1
      click_list(ev[:x].to_i - @user_area_x0, ev[:y].to_i - @user_area_y0)
    elsif t == :mouse_wheel
      scroll(ev[:delta].to_i > 0 ? -1 : 1)
    elsif t == :key_down
      key(ev[:scancode].to_i, ev[:character].to_i)
    end
    @ui.flush
  end

  def on_destroy
    @pw = ""
    save_crt if @crt_dirty
  end

  private

  # The page asked for (FmrbApp.settings_page's low two bits); Display
  # only where the look can be drawn.
  def ask_page(ask)
    p = ask & 3
    return :bt if p == 1
    return :display if p == 2 && @crt_here
    :wifi
  end

  def page_name(page)
    return "Wi-Fi" if page == :wifi
    return "Bluetooth" if page == :bt
    "Display"
  end

  # ---- widgets

  def build_widgets
    @ui = FmrbUI.new(self)
    tw = 56
    @ui.toggle(:tab_wifi, 2, 2, tw, 14, FmrbI18n.t(:st_wifi), group: :page, on: @page == :wifi)
    @ui.toggle(:tab_bt, 2 + tw + 4, 2, tw + 10, 14, FmrbI18n.t(:st_bt), group: :page, on: @page == :bt)
    if @crt_here
      @ui.toggle(:tab_disp, 2 + tw * 2 + 18, 2, tw + 10, 14, FmrbI18n.t(:st_display), group: :page,
                 on: @page == :display)
      lx = 92
      @ui.toggle(:look_sharp, lx, 20, 72, 14, FmrbI18n.t(:st_sharp), group: :look, on: !@crt_on)
      @ui.toggle(:look_crt, lx + 78, 20, 72, 14, FmrbI18n.t(:st_crt), group: :look, on: @crt_on)
      i = 0
      while i < CRT_KEYS.size
        @ui.stepper(crt_id(i), CRT_COLS[crt_col(i)][1], crt_row_y(i), CRT_STEP_W, 14, @crt_s[i], 0, 100, 5)
        i += 1
