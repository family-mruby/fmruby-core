    @ui.button(:scan, 4 + (bw + 6) * 2, by, bw, 16, FmrbI18n.t(:st_scan))
    @ui.button(:power, @w - 64, 18, 60, 13, FmrbI18n.t(:st_bt_off))
    show_widgets
  end

  def show_widgets
    wifi = @page == :wifi
    disp = @page == :display
    @ui.set_visible(:scan, wifi)
    @ui.set_visible(:power, @page == :bt)
    @ui.set_visible(:connect, !disp)
    @ui.set_visible(:disconnect, !disp)
    return unless @crt_here
    @ui.set_visible(:look_sharp, disp)
    @ui.set_visible(:look_crt, disp)
    i = 0
    while i < CRT_KEYS.size
      @ui.set_visible(crt_id(i), disp)
      i += 1
    end
    @ui.set_visible(:crt_standard, disp)
    @ui.set_visible(:crt_strong, disp)
  end

  def crt_id(i)
    CRT_IDS[i]
  end

  def crt_col(i)
    i < CRT_COL_ROWS ? 0 : 1
  end

  def crt_row_y(i)
    CRT_ROW_Y + (i < CRT_COL_ROWS ? i : i - CRT_COL_ROWS) * CRT_ROW_H
  end

  def switch_page(page)
    return if page == @page
    @page = page
    @sel = 0
    @sel_name = nil
    @top = 0
    @msg = ""
    @ui.set_on(:tab_wifi, page == :wifi)
    @ui.set_on(:tab_bt, page == :bt)
    @ui.set_on(:tab_disp, page == :display) if @crt_here
    show_widgets
    read_state(true)
    draw_page
  end

  def act(id)
    case id
    when :tab_wifi then switch_page(:wifi)
    when :tab_bt then switch_page(:bt)
    when :tab_disp then switch_page(:display)
    when :look_sharp then crt_change(false, nil)
    when :look_crt then crt_change(true, nil)
    when :crt_standard then crt_change(@crt_on, CRT_STANDARD)
    when :crt_strong then crt_change(@crt_on, CRT_STRONG)
    when :crt_scanline, :crt_mask, :crt_glow, :crt_curve, :crt_vignette, :crt_ntsc, :crt_flicker, :crt_noise
      st = []
      i = 0
      while i < CRT_KEYS.size
        st << @ui.value(crt_id(i))
        i += 1
      end
      crt_change(@crt_on, st)
    when :scan
      @wifi_text = FmrbApp.wifi_networks(true)
      parse_wifi
      draw_page
    when :connect then do_connect
    when :disconnect then do_disconnect
    when :power
      FmrbApp.bt_power(!@bt_powered)
      draw_page
    end
  end

  # ---- state

  # Reads the page's state; true when it changed.
  def read_state(force)
    if @page == :display
      t = FmrbApp.crt_state
      return false if !force && t == @crt_text
      @crt_text = t
      parse_crt
      sync_crt_widgets
      Log.info("settings: display #{t == '' ? 'unavailable' : t}")
    elsif @page == :wifi
      t = FmrbApp.wifi_networks(false)
      return false if !force && t == @wifi_text
      @wifi_text = t
      parse_wifi
      log_state("wifi", @wifi_head, @aps)
    else
      t = FmrbApp.bt_devices
      return false if !force && t == @bt_text
      @bt_text = t
      parse_bt
      log_state("bt", @bt_head, @devs)
    end
    true
  end

  # "crt,55,30,30,15,40,0,0,0" (FmrbApp.crt_state) -> @crt_on, @crt_s; ""
  # (the look cannot be drawn) keeps the defaults.
  def parse_crt
    f = @crt_text.split(",")
    @crt_on = f[0] == "crt"
    @crt_s = []
    i = 0
    while i < CRT_KEYS.size
      v = f[i + 1]
      @crt_s << (v.nil? || v.empty? ? CRT_DEFAULTS[i] : v.to_i)
      i += 1
    end
  end

  def sync_crt_widgets
    return unless @crt_here
    @ui.set_on(:look_sharp, !@crt_on)
    @ui.set_on(:look_crt, @crt_on)
    i = 0
    while i < CRT_KEYS.size
      @ui.set_value(crt_id(i), @crt_s[i])
      i += 1
    end
  end

  # A change on the Display page: to the compositor now, to the file on the
  # next tick (a run of steps writes once).
  def crt_change(on, strengths)
    @crt_on = on
    @crt_s = strengths.dup if strengths
    sync_crt_widgets
    ok = FmrbApp.crt_set(@crt_on, @crt_s[0], @crt_s[1], @crt_s[2], @crt_s[3], @crt_s[4],
                         @crt_s[5], @crt_s[6], @crt_s[7])
    @msg = ok ? FmrbI18n.t(:st_crt_kept) : FmrbI18n.t(:st_crt_gone)
    @crt_dirty = ok
    Log.info("settings: display asked #{@crt_on ? 'crt' : 'sharp'} #{@crt_s.join(',')}#{ok ? '' : ' (not available)'}")
    draw_page
  end

  # The [crt] table of /etc/system_conf.toml: the old one (header to the
  # next header) taken out, the new one put at the end. The other lines stay
  # as they are; written beside the file and renamed over it, as the
  # desktop's Config does.
  def save_crt
    @crt_dirty = false
    lines = []
    begin
      f = File.open(CONF_PATH, "r")
      content = f.read
      f.close
      lines = content.split("\n", -1)
    rescue => e
      Log.warn("settings: cannot read #{CONF_PATH}: #{e.message}")
      return
    end
    out = []
    in_crt = false
    lines.each do |raw|
      st = raw.strip
      if st.start_with?("[")
        in_crt = st == "[crt]"
        next if in_crt
      end
      out << raw unless in_crt
    end
    out.pop while out.size > 0 && out[out.size - 1].strip.empty?
    out << ""
    out << "[crt]"
    out << "# the CRT look chosen in the settings window (doc/web_crt); beats the session file's --set"
    out << "look = \"#{@crt_on ? 'crt' : 'sharp'}\""
    i = 0
    while i < CRT_KEYS.size
      out << "#{CRT_KEYS[i]} = #{@crt_s[i]}"
      i += 1
    end
    out << ""
    tmp = CONF_PATH + ".tmp"
    begin
      f = File.open(tmp, "w")
      f.write(out.join("\n"))
      f.close
      File.rename(tmp, CONF_PATH)
      Log.info("settings: display kept in #{CONF_PATH} [crt]")
    rescue => e
      Log.error("settings: cannot write #{CONF_PATH}: #{e.message}")
    end
  end

  # One line per change, for the log (and the checks): the state fields and
  # the names in the list ("*" active or connected).
  def log_state(what, head, rows)
    names = []
    i = 0
    while i < rows.size
      r = rows[i]
      if what == "wifi"
        names << "#{r[0]}#{r[3] ? '*' : ''}"
      else
        names << "#{r[1]}#{r[2] ? '*' : ''}"
      end
      i += 1
    end
    Log.info("settings: #{what} #{head[1]} [#{head[2]}] [#{head[3]}] [#{head[4]}] [#{head[5]}] #{names.join(',')}")
  end

  # The tab-separated fields; empty ones at the end are kept (as "").
  def fields(line)
    f = line.split("\t")
    f << "" while f.size < 6
    f
  end

  def parse_wifi
    @aps = []
    @wifi_head = ["wifi", "starting", "", "", "", ""]
    return if @wifi_text.nil? || @wifi_text.empty?
    lines = @wifi_text.split("\n")
    i = 0
    while i < lines.size
      f = fields(lines[i])
      if f[0] == "wifi"
        @wifi_head = f
      elsif f[0] == "ap" && f.size >= 6
        @aps << [f[1], f[2].to_i, f[3] == "1", f[4] == "1", f[5] == "1"]
      end
      i += 1
    end
    keep_selection(@aps, 0)
  end

  def parse_bt
    @devs = []
    @bt_head = ["bt", "starting", "0", "", "", ""]
    return if @bt_text.nil? || @bt_text.empty?
    lines = @bt_text.split("\n")
    i = 0
    while i < lines.size
      f = fields(lines[i])
      if f[0] == "bt"
        @bt_head = f
      elsif f[0] == "dev" && f.size >= 4
        @devs << [f[1], f[2], f[3] == "1", f[4].to_s]
      end
      i += 1
    end
    @bt_powered = @bt_head[2] == "1"
    @ui.set_text(:power, FmrbI18n.t(@bt_powered ? :st_bt_off : :st_bt_on))
    keep_selection(@devs, 0)
  end

  # The selection follows its network or device when the list reorders
  # (the one connected moves to the top).
  def keep_selection(rows, key)
    if @sel_name
      i = 0
      while i < rows.size
        if rows[i][key] == @sel_name
          @sel = i
          break
        end
        i += 1
      end
    end
    fix_selection(rows.size)
    r = rows[@sel]
    @sel_name = r ? r[key] : nil
  end

  def fix_selection(n)
    @sel = n - 1 if @sel >= n
    @sel = 0 if @sel < 0
    @top = @sel if @sel < @top
    @top = @sel - ROWS + 1 if @sel >= @top + ROWS
    @top = 0 if @top < 0
  end

  def head(i)
    h = @page == :wifi ? @wifi_head : @bt_head
    (h && h[i]) || ""
  end

  def fmt(key, arg)
    FmrbI18n.t(key).sub("%s", arg.to_s)
  end

  # ---- actions

  def selected_ap
    @aps[@sel]
  end

  # The password field shows for a secured network NetworkManager has not
  # saved, and after an attempt said the password was wanted or wrong.
  def needs_password?
    return false unless @page == :wifi
    ap = selected_ap
    return false if ap.nil?
    code = head(4)
    asked = (code == "need_password" || code == "auth_failed") && head(5) == ap[0]
    (ap[2] && !ap[4]) || asked
  end

  def do_connect
    if @page == :wifi
      ap = selected_ap
      return if ap.nil?
      if needs_password? && @pw.empty?
        @msg = FmrbI18n.t(:st_type_password)
        draw_page
        return
      end
      pw = @pw
      @pw = ""
      FmrbApp.wifi_connect(ap[0], pw)
      pw = nil
      @msg = ""
    else
      d = @devs[@sel]
      return if d.nil?
      FmrbApp.bt_connect(d[0], true)
    end
    read_state(true)
    draw_page
  end

  def do_disconnect
    if @page == :wifi
      FmrbApp.wifi_disconnect
    else
      d = @devs[@sel]
      return if d.nil?
      FmrbApp.bt_connect(d[0], false)
    end
    read_state(true)
    draw_page
  end

  def click_list(x, y)
    return if @page == :display
    return if y < LIST_Y || y >= LIST_Y + ROWS * ROW_H
    i = @top + (y - LIST_Y) / ROW_H
    n = @page == :wifi ? @aps.size : @devs.size
    return if i >= n
    select(i)
  end

  def select(i)
    return if i == @sel
    @sel = i
    @pw = ""
    @msg = ""
    rows = @page == :wifi ? @aps : @devs
    fix_selection(rows.size)
    r = rows[@sel]
    @sel_name = r ? r[0] : nil
    draw_page
  end

  def scroll(d)
    return if @page == :display
    n = @page == :wifi ? @aps.size : @devs.size
    t = @top + d
    t = n - ROWS if t > n - ROWS
    t = 0 if t < 0
    return if t == @top
    @top = t
    draw_page
  end

  def key(sc, ch)
    return if @page == :display
    n = @page == :wifi ? @aps.size : @devs.size
    if sc == FmrbConst::KEY_UP
      select(@sel - 1) if @sel > 0
    elsif sc == FmrbConst::KEY_DOWN
      select(@sel + 1) if @sel + 1 < n
    elsif ch == 13 || ch == 10
      do_connect
    elsif needs_password?
      if ch == 8
        @pw = @pw[0, @pw.length - 1] if @pw.length > 0
        draw_page
      elsif ch >= 32 && ch <= 126 && @pw.length < 63
        @pw = @pw + ch.chr
        draw_page
      end
    end
  end

  # ---- drawing

  def ax(x)
    @user_area_x0 + x
  end

  def ay(y)
    @user_area_y0 + y
  end

  def draw_page
    clear_user_area
    if @page == :wifi
      draw_wifi
    elsif @page == :bt
      draw_bt
    else
      draw_display
    end
    @ui.invalidate_all
    @ui.flush
  end

  def text(x, y, s, color = nil)
    @gfx.draw_text(ax(x), ay(y), s, color || theme_fg, theme_bg, mixed: true)
  end

  def fit(s, px)
    FmrbI18n.truncate_to(s.to_s, px)
  end

  def status_line(y, s)
    text(4, y, fit(s, @w - 8))
  end

  def draw_wifi
    st = head(1)
    line = case st
           when "none" then FmrbI18n.t(:st_wifi_no_nm)
           when "nodevice" then FmrbI18n.t(:st_wifi_no_dev)
           when "off" then FmrbI18n.t(:st_wifi_off)
           when "starting" then FmrbI18n.t(:st_wifi_starting)
           else
             head(2).empty? ? FmrbI18n.t(:st_wifi_none_used) : fmt(:st_wifi_using, head(2))
           end
    status_line(20, line)
    if st == "ok" && @aps.empty?
      text(8, LIST_Y + 2, FmrbI18n.t(:st_wifi_empty), theme_border)
    end
    i = 0
    while i < ROWS
      k = @top + i
      break if k >= @aps.size
      draw_ap_row(LIST_Y + i * ROW_H, @aps[k], k == @sel)
      i += 1
    end
    draw_scroll_mark(@aps.size)
    py = LIST_Y + ROWS * ROW_H + 3
    if needs_password?
      text(4, py + 2, FmrbI18n.t(:st_password))
      bx = 70
      bw = @w - bx - 6
      @gfx.fill_rect(ax(bx), ay(py), bw, 12, theme_fg_light)
      @gfx.draw_rect(ax(bx), ay(py), bw, 12, theme_accent)
      stars = "*" * @pw.length
      stars = stars[stars.length - 30, 30] if stars.length > 30
      @gfx.draw_text(ax(bx + 2), ay(py + 2), stars, theme_fg, theme_fg_light)
    end
    draw_message(wifi_outcome)
  end

  def wifi_outcome
    return @msg unless @msg.empty?
    busy = head(3)
    return fmt(:st_connecting, head(5)) if busy == "connecting"
    return FmrbI18n.t(:st_scanning) if busy == "scanning"
    code = head(4)
    arg = head(5)
    case code
    when "connected" then fmt(:st_connected, arg)
    when "disconnected" then FmrbI18n.t(:st_disconnected)
    when "need_password" then fmt(:st_need_password, arg)
    when "auth_failed" then fmt(:st_auth_failed, arg)
    when "no_network" then fmt(:st_no_network, arg)
    when "enterprise" then fmt(:st_enterprise, arg)
    when "failed" then fmt(:st_failed, arg)
    when "refused" then fmt(:st_refused, arg)
    else ""
    end
  end

  def draw_ap_row(y, ap, selected)
    bg = selected ? theme_accent : theme_bg
    fg = selected ? theme_fg_light : theme_fg
    @gfx.fill_rect(ax(2), ay(y), @w - 12, ROW_H, bg)
    # the strength: four bars
    bars = (ap[1] + 12) / 25
    bars = 4 if bars > 4
    j = 0
    while j < 4
      bh = 2 + j * 2
      c = j < bars ? fg : (selected ? theme_fg_light : theme_border)
      if j < bars
        @gfx.fill_rect(ax(5 + j * 3), ay(y + 10 - bh), 2, bh, c)
      else
        @gfx.fill_rect(ax(5 + j * 3), ay(y + 9), 2, 1, c)
      end
      j += 1
    end
    name = ap[0]
    name = "> " + name if ap[3]
    right = ""
    right = FmrbI18n.t(:st_saved) if ap[4]
    rw = FmrbI18n.text_width(right)
    @gfx.draw_text(ax(20), ay(y + 2), fit(name, @w - 50 - rw), fg, bg, mixed: true)
    if ap[2]
      # a lock: a small box with a loop
      lx = @w - 20
      @gfx.fill_rect(ax(lx), ay(y + 5), 6, 5, fg)
      @gfx.draw_rect(ax(lx + 1), ay(y + 2), 4, 4, fg)
    end
    @gfx.draw_text(ax(@w - 24 - rw), ay(y + 2), right, fg, bg, mixed: true) unless right.empty?
  end

  def draw_scroll_mark(n)
    return if n <= ROWS
    x = @w - 8
    top = LIST_Y
    h = ROWS * ROW_H
    @gfx.fill_rect(ax(x), ay(top), 3, h, theme_border)
    th = h * ROWS / n
    th = 6 if th < 6
    ty = top + (h - th) * @top / (n - ROWS)
    @gfx.fill_rect(ax(x), ay(ty), 3, th, theme_fg)
  end

  def draw_message(s)
    return if s.nil? || s.empty?
    text(4, @h - 14, fit(s, @w - 8), theme_accent)
  end

  def draw_bt
    st = head(1)
    line = case st
           when "none" then FmrbI18n.t(:st_bt_none)
           when "starting" then FmrbI18n.t(:st_bt_starting)
           else FmrbI18n.t(@bt_powered ? :st_bt_is_on : :st_bt_is_off)
           end
    status_line(20, line)
    @ui.set_visible(:power, st == "ok")
    if st == "ok" && @devs.empty?
      text(8, LIST_Y + 2, FmrbI18n.t(:st_bt_empty), theme_border)
    end
    i = 0
    while i < ROWS
      k = @top + i
      break if k >= @devs.size
      d = @devs[k]
      y = LIST_Y + i * ROW_H
      sel = k == @sel
      bg = sel ? theme_accent : theme_bg
      fg = sel ? theme_fg_light : theme_fg
      @gfx.fill_rect(ax(2), ay(y), @w - 12, ROW_H, bg)
      @gfx.fill_circle(ax(8), ay(y + 6), 3, fg) if d[2]
      @gfx.draw_circle(ax(8), ay(y + 6), 3, fg) unless d[2]
      @gfx.draw_text(ax(16), ay(y + 2), fit(d[1], @w - 110), fg, bg, mixed: true)
      @gfx.draw_text(ax(@w - 96), ay(y + 2), d[0], fg, bg, mixed: true)
      i += 1
    end
    draw_scroll_mark(@devs.size)
    text(4, LIST_Y + ROWS * ROW_H + 4, fit(FmrbI18n.t(:st_bt_pair), @w - 8), theme_border)
    draw_message(bt_outcome)
  end

  def draw_display
    if @crt_text == ""
      status_line(20, FmrbI18n.t(:st_crt_gone))
      return
    end
    text(4, 23, FmrbI18n.t(:st_look))
    i = 0
    while i < CRT_KEYS.size
      text(CRT_COLS[crt_col(i)][0], crt_row_y(i) + 3, FmrbI18n.t(("st_" + CRT_KEYS[i]).to_sym))
      i += 1
    end
    draw_message(@msg)
  end

  def bt_outcome
    busy = head(3)
    unless busy.empty?
      name = busy
      i = 0
      while i < @devs.size
        name = @devs[i][1] if @devs[i][0] == busy
        i += 1
      end
      return fmt(:st_bt_busy, name)
    end
    arg = head(5)
    case head(4)
    when "connected" then fmt(:st_bt_connected, arg)
    when "disconnected" then fmt(:st_bt_disconnected, arg)
    when "failed" then fmt(:st_bt_failed, arg)
    when "power_failed" then fmt(:st_bt_power_failed, arg)
    when "powered_on" then FmrbI18n.t(:st_bt_powered_on)
    when "powered_off" then FmrbI18n.t(:st_bt_powered_off)
    else ""
    end
  end
end

