// crt.js - the browser build's CRT look (doc/web_crt/).
//
// The machine's picture stays where it is: main.js keeps painting the 2D
// canvas (#screen), and that canvas is what screenshots and the regression
// read. This file draws a second canvas over it with WebGL2 -- scanlines, a
// phosphor grille, glow, the tube's curve and its dark corners, NTSC's
// colour bleed -- and only when the picture, the size or a setting has
// changed; with the time effects (flicker, noise) on, TIME_FPS times a second.
//
// The curve is one formula, written three times: warpToSource below
// (JavaScript, which main.js uses to send a click to the pixel under the
// pointer), the same lines in the fragment shader, and hosted/crt/crt_warp.c
// (the native compositor's pointer; rake webcrt:test holds it to this one). Both go from the display to the
// picture, which is the direction a fragment shader works in, so a click
// lands on exactly the pixel drawn under it. warpToDisplay is the other
// way, solved by a few Newton steps (the tests and the driver use it).
//
// Loaded as a plain script in the page (window.FmrbCrt) and as a CommonJS
// module under node (test/web_crt/).
(function (root) {
  'use strict';

  // Slider value (0..100) -> the curve's coefficient. 100 is a strongly
  // bent tube; the default is a gentle one.
  const CURVE_MAX = 0.25;

  // The sets of strengths, 0..100 each: Standard, which is also what a fresh
  // page gets (chosen by the user on the GPD, doc/web_crt C6), and Strong,
  // which a demo shows best (C6b). NTSC's colour bleed, flicker and noise
  // are 0 in Standard: the look is the clean one unless asked, and with
  // flicker or noise on the view draws TIME_FPS times a second, not only on
  // change. One table for this page and the native PC settings.
  // BEGIN presets generated by rake webcrt:gen from hosted/crt/crt_presets.h (edit that, not this)
  const PRESETS = Object.freeze({
    standard: Object.freeze({ scan: 55, mask: 30, glow: 30, curve: 15, vignette: 40, ntsc: 0, flicker: 0, noise: 0 }),
    strong: Object.freeze({ scan: 75, mask: 50, glow: 45, curve: 25, vignette: 55, ntsc: 50, flicker: 50, noise: 50 }),
  });
  // END presets generated by rake webcrt:gen
  const DEFAULTS = PRESETS.standard;
  const KEYS = Object.freeze(['scan', 'mask', 'glow', 'curve', 'vignette', 'ntsc', 'flicker', 'noise']);
  const TIME_FPS = 30;

  // Flicker or noise asked for: the picture changes with time.
  function timed(s) {
    return (s.flicker || 0) > 0 || (s.noise || 0) > 0;
  }

  // The time effects' frame number at a moment (ms): TIME_FPS a second,
  // wrapped well inside a float's exact integers.
  function timeFrame(ms) {
    return Math.floor(ms * TIME_FPS / 1000) % 1048576;
  }

  function curveCoef(curve) {
    return Math.max(0, Math.min(100, curve || 0)) / 100 * CURVE_MAX;
  }

  // Display position (0..1 across the shown canvas, y down) -> picture
  // position (0..1, y down). Radial: d' = d * (1 + c * |d|^2) with d in
  // -1..1, so the whole picture stays on the display and only the space
  // around its bowed edges is outside (> 1 or < 0: nothing is drawn there).
  function warpToSource(u, v, curve) {
    const c = curveCoef(curve);
    if (c === 0) return [u, v];
    const dx = u * 2 - 1, dy = v * 2 - 1;
    const k = 1 + c * (dx * dx + dy * dy);
    return [(dx * k + 1) / 2, (dy * k + 1) / 2];
  }

  // Picture position -> display position: the inverse of warpToSource.
  // Along a ray from the centre, |s| = r + c r^3 is solved for r (monotonic,
  // so Newton from r = |s| settles in a handful of steps).
  function warpToDisplay(x, y, curve) {
    const c = curveCoef(curve);
    if (c === 0) return [x, y];
    const sx = x * 2 - 1, sy = y * 2 - 1;
    const s = Math.hypot(sx, sy);
    if (s === 0) return [0.5, 0.5];
    let r = s;
    for (let i = 0; i < 12; i++) {
      const f = r + c * r * r * r - s;
      r -= f / (1 + 3 * c * r * r);
    }
    const t = r / s;
    return [(sx * t + 1) / 2, (sy * t + 1) / 2];
  }

  // Inside the picture? (0 <= p < 1 on both axes)
  function inside(p) {
    return p[0] >= 0 && p[0] < 1 && p[1] >= 0 && p[1] < 1;
  }

  // How strongly the fine-grained effects may show at a given magnification
  // (display pixels per picture pixel, device pixels included). Below ~1.5
  // a scanline is narrower than a display pixel and only makes moire; by 3
  // it has room. The same formula for every resolution.
  function fineWeight(scale, lo, hi) {
    const t = Math.max(0, Math.min(1, (scale - lo) / (hi - lo)));
    return t * t * (3 - 2 * t);
  }

  // The shaders (GLSL ES 3.00) are shared with the native compositor:
  // hosted/crt/crt.vert and crt.frag are the source.
  // BEGIN generated by rake webcrt:gen from hosted/crt/ (edit those, not this)
  const VERT = `#version 300 es
// crt.vert - the CRT look's vertex shader (doc/web_crt/): one triangle
// over the whole target. GLSL ES 3.00 without its #version line, which the
// users put first: the browser build (wasm/web/crt.js, written in by
// rake webcrt:gen) and the native compositor (native/wlr/wl_crt.c, through
// a header CMake makes).
in vec2 a_pos;
void main() { gl_Position = vec4(a_pos, 0.0, 1.0); }
`;

  const FRAG = `#version 300 es
// crt.frag - the CRT look's fragment shader (doc/web_crt/), shared by the
// browser build (wasm/web/crt.js) and the native compositor
// (native/wlr/wl_crt.c). GLSL ES 3.00 without its #version line.
//
// The curve is the formula of crt_warp.c and crt.js's warpToSource (display
// -> picture); change all three together (rake webcrt:test compares them).
//
// The browser draws the picture itself (u_src pixels) into the default
// framebuffer. The native compositor defines FMRB_CRT_OUTPUT: it draws the
// whole output, already composited by wlroots into a buffer at the output's
// resolution, into the output's buffer; a picture pixel is display.scale
// output pixels (u_unit) and both buffers may be turned (u_frag, u_texel).
//
// Uniforms that are 0 skip their effect (a uniform branch: every fragment
// takes the same way, so it costs nothing to ask).
precision highp float;
uniform sampler2D u_tex;
uniform vec2 u_src;      // picture size, pixels
uniform vec2 u_dst;      // display size, device pixels
uniform float u_curve;   // curve coefficient (warpToSource's c)
uniform float u_scan;    // scanline strength, already weighted by magnification
uniform float u_mask;    // grille strength, likewise
uniform float u_glow;    // glow strength
uniform float u_vig;     // dark corners
uniform float u_ntsc;    // NTSC colour bleed (the colour's resolution across)
uniform float u_flicker; // brightness that wavers from frame to frame
uniform float u_noise;   // grain, new every frame
uniform float u_frame;   // the time effects' frame number (30 a second)
#ifdef FMRB_CRT_OUTPUT
uniform mat3 u_frag;     // gl_FragCoord -> display position (0..1, y down)
uniform mat3 u_texel;    // output pixel (logical, its centre) -> texel of u_tex
uniform vec2 u_out;      // the output's logical size, pixels
uniform float u_unit;    // output pixels per picture pixel
#endif
out vec4 o_color;

#ifdef FMRB_CRT_OUTPUT
// The output pixel under the fragment as wlroots composited it, in texels
// of u_tex, and a picture pixel's step right and down (set in main).
vec2 t_base, t_dx, t_dy;
ivec2 t_max;
// A neighbour o picture pixels away (clamped at the output's edge).
vec3 px(ivec2 o) {
  ivec2 t = ivec2(floor(t_base + float(o.x) * t_dx + float(o.y) * t_dy));
  return texelFetch(u_tex, clamp(t, ivec2(0), t_max), 0).rgb;
}
#define AT(o) px(o)
#else
vec3 px(ivec2 p) {
  p = clamp(p, ivec2(0), ivec2(u_src) - 1);
  return texelFetch(u_tex, p, 0).rgb;
}
#define AT(o) px(ip + (o))
#endif

// RGB <-> YIQ (NTSC's luma and two colour-difference signals).
const mat3 TO_YIQ = mat3(0.299, 0.596, 0.211,
                         0.587, -0.274, -0.523,
                         0.114, -0.322, 0.312);
const mat3 TO_RGB = mat3(1.0, 1.0, 1.0,
                         0.956, -0.272, -1.106,
                         0.621, -0.647, 1.703);

// A hash of a picture pixel and a frame, 0..1 (pcg3d).
float hash(uvec3 v) {
  v = v * 1664525u + 1013904223u;
  v.x += v.y * v.z; v.y += v.z * v.x; v.z += v.x * v.y;
  v ^= v >> 16u;
  v.x += v.y * v.z; v.y += v.z * v.x; v.z += v.x * v.y;
  return float(v.x >> 8u) / 16777215.0;
}

void main() {
#ifdef FMRB_CRT_OUTPUT
  vec2 uv = (u_frag * vec3(gl_FragCoord.xy, 1.0)).xy;
#else
  vec2 uv = vec2(gl_FragCoord.x / u_dst.x, 1.0 - gl_FragCoord.y / u_dst.y);
#endif
  vec2 st = uv;
  if (u_curve > 0.0) {
    vec2 d = uv * 2.0 - 1.0;
    d *= 1.0 + u_curve * dot(d, d);
    st = d * 0.5 + 0.5;
  }
  if (st.x < 0.0 || st.y < 0.0 || st.x >= 1.0 || st.y >= 1.0) {
    o_color = vec4(0.0, 0.0, 0.0, 1.0);
    return;
  }
  vec2 p = st * u_src;
#ifdef FMRB_CRT_OUTPUT
  // The output pixel under this one; the neighbours are a picture pixel away.
  vec2 lp = floor(st * u_out) + 0.5;
  t_base = (u_texel * vec3(lp, 1.0)).xy;
  t_dx = mat2(u_texel)[0] * u_unit;
  t_dy = mat2(u_texel)[1] * u_unit;
  t_max = textureSize(u_tex, 0) - 1;
#else
  ivec2 ip = ivec2(floor(p));
#endif
  vec3 c = AT(ivec2(0, 0));
  if (u_ntsc > 0.0) {
    // A composite signal carries the colour in about a third of the
    // brightness's band: keep this pixel's luma, take the colour (I and Q)
    // from a gaussian along the row (sigma 3 picture pixels, out to 7 each
    // way; the far taps stand for their neighbours too), so colour spills
    // 2-4 pixels past its edges. Where the brightness steps, the colour
    // decoder also sees the step as colour: a fringe whose hue turns with
    // the subcarrier's phase (about 0.6 of a cycle a pixel, half a cycle a
    // line).
    // The decoder's filter also lags, so the colour trails to the right:
    // a pixel takes more from its left and less from its right.
    //
    // Strength: e = 2 * u_ntsc. The blur is all in by e = 1 (the strength
    // 50); above it the lag and the fringe keep growing (the strength 100
    // all from the left, the fringe twice as strong).
    vec3 l1 = AT(ivec2(-1, 0)), r1 = AT(ivec2(1, 0));
    vec3 lw = l1 * 0.1259 + AT(ivec2(-2, 0)) * 0.1067 + AT(ivec2(-3, 0)) * 0.0810
            + AT(ivec2(-5, 0)) * 0.0994 + AT(ivec2(-7, 0)) * 0.0205;
    vec3 rw = r1 * 0.1259 + AT(ivec2(2, 0)) * 0.1067 + AT(ivec2(3, 0)) * 0.0810
            + AT(ivec2(5, 0)) * 0.0994 + AT(ivec2(7, 0)) * 0.0205;
    float e = 2.0 * u_ntsc;
    float lag = min(0.6 * e, 1.0);
    vec2 iq = (TO_YIQ * (c * 0.1330 + lw * (1.0 + lag) + rw * (1.0 - lag))).yz;
    vec3 yiq = TO_YIQ * c;
    vec2 pp = floor(p);
    float phase = 6.2832 * (0.6 * pp.x + 0.5 * pp.y);
    float ystep = dot(r1 - l1, vec3(0.299, 0.587, 0.114));
    float blend = sqrt(min(e, 1.0));
    iq += 0.8 * e / blend * ystep * vec2(cos(phase), sin(phase));
    c = clamp(TO_RGB * vec3(yiq.x, mix(yiq.yz, iq, blend)), 0.0, 1.0);
  }
  if (u_noise > 0.0) {
    // Grain in the signal: each picture pixel brighter or darker (+-14% at
    // 100), new every frame. Before the scanlines and the grille, so a
    // grain is shaped like the picture's pixel it falls on.
    float n = hash(uvec3(uvec2(ivec2(floor(p)) + 4096), uint(u_frame))) - 0.5;
    c = clamp(c + vec3(n * u_noise * 0.28), 0.0, 1.0);
  }
  vec3 halo = vec3(0.0);
  if (u_glow > 0.0) {
    // A beam spreads sideways: mix in the neighbours on the row ...
    vec3 l = AT(ivec2(-1, 0));
    vec3 r = AT(ivec2(1, 0));
    c = mix(c, 0.5 * c + 0.25 * (l + r), 0.6 * u_glow);
    // ... and bright areas light up their surroundings, filling the gaps
    // the scanlines and the grille leave (added after them).
    halo = 0.16 * (l + r)
         + 0.12 * (AT(ivec2(0, -1)) + AT(ivec2(0, 1)))
         + 0.06 * (AT(ivec2(-2, 0)) + AT(ivec2(2, 0))
                 + AT(ivec2(-1, -1)) + AT(ivec2(1, -1))
                 + AT(ivec2(-1, 1)) + AT(ivec2(1, 1)));
    halo = halo * halo;
  }
  if (u_scan > 0.0) {
    // One beam per picture row, a gaussian across it; a bright pixel
    // widens its beam, so light text stays solid while dark rows open up.
    float lum = dot(c, vec3(0.299, 0.587, 0.114));
    float sigma = mix(0.20, 0.38, lum);
    float fy = fract(p.y) - 0.5;
    float beam = exp(-fy * fy / (2.0 * sigma * sigma));
    float gain = 1.0 / min(1.0, sigma * 2.5066);
    c = mix(c, c * beam * mix(1.0, gain, 0.7), u_scan);
  }
  if (u_mask > 0.0) {
    // Aperture grille: R, G and B stripes, three to a picture pixel.
    int stripe = int(fract(p.x) * 3.0);
    vec3 m = vec3(0.45);
    m[stripe] = 1.0;
    c *= mix(vec3(1.0), m, u_mask) / mix(1.0, 0.7, u_mask);
  }
  c += halo * u_glow * 0.9;
  if (u_flicker > 0.0) {
    // The whole picture brighter or darker each frame (+-12% at 100), and
    // a dark bar rolling down the screen once in 4 seconds (mains hum):
    // about a sixth of the height, 60% darker at its middle at 100.
    uint f = uint(u_frame);
    float w = hash(uvec3(f, 7u, 11u)) * 2.0 - 1.0;
    float dy = fract(st.y - u_frame / 120.0 + 0.5) - 0.5;
    float bar = exp(-dy * dy / (2.0 * 0.06 * 0.06));
    c *= 1.0 + u_flicker * (0.12 * w - 0.6 * bar);
  }
  if (u_vig > 0.0) {
    float v = 16.0 * st.x * st.y * (1.0 - st.x) * (1.0 - st.y);
    c *= pow(clamp(v, 0.0, 1.0), 0.45 * u_vig);
  }
  o_color = vec4(clamp(c, 0.0, 1.0), 1.0);
}
`;
  // END generated by rake webcrt:gen

  // The view: a WebGL2 canvas laid over the 2D one. create() gives null (and
  // says why on one console line) where WebGL2 or the shader is refused, and
  // the page keeps its plain look.
  function create(glCanvas) {
    let gl = null;
    try {
      gl = glCanvas.getContext('webgl2', { alpha: false, antialias: false, depth: false,
                                           stencil: false, premultipliedAlpha: false,
                                           preserveDrawingBuffer: false });
    } catch (e) { gl = null; }
    if (!gl) {
      console.warn('fmrb: CRT look unavailable: no WebGL2');
      return null;
    }
    function shader(type, src) {
      const s = gl.createShader(type);
      gl.shaderSource(s, src);
      gl.compileShader(s);
      if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) {
        throw new Error(gl.getShaderInfoLog(s) || 'compile failed');
      }
      return s;
    }
    let prog;
    try {
      prog = gl.createProgram();
      gl.attachShader(prog, shader(gl.VERTEX_SHADER, VERT));
      gl.attachShader(prog, shader(gl.FRAGMENT_SHADER, FRAG));
      gl.linkProgram(prog);
      if (!gl.getProgramParameter(prog, gl.LINK_STATUS)) {
        throw new Error(gl.getProgramInfoLog(prog) || 'link failed');
      }
    } catch (e) {
      console.warn('fmrb: CRT look unavailable: shader: ' + (e && e.message ? e.message : e));
      return null;
    }
    gl.useProgram(prog);
    const buf = gl.createBuffer();
    gl.bindBuffer(gl.ARRAY_BUFFER, buf);
    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);
    const aPos = gl.getAttribLocation(prog, 'a_pos');
    gl.enableVertexAttribArray(aPos);
    gl.vertexAttribPointer(aPos, 2, gl.FLOAT, false, 0, 0);
    const U = {};
    for (const n of ['u_tex', 'u_src', 'u_dst', 'u_curve', 'u_scan', 'u_mask', 'u_glow', 'u_vig',
                     'u_ntsc', 'u_flicker', 'u_noise', 'u_frame']) {
      U[n] = gl.getUniformLocation(prog, n);
    }
    const tex = gl.createTexture();
    gl.activeTexture(gl.TEXTURE0);
    gl.bindTexture(gl.TEXTURE_2D, tex);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.NEAREST);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.NEAREST);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
    gl.pixelStorei(gl.UNPACK_ALIGNMENT, 1);
    gl.uniform1i(U.u_tex, 0);

    let texW = 0, texH = 0;
    let pending = null;      // an ImageData to upload before the next draw
    let dirty = false;       // draw on the next flush
    let lost = false;
    let settings = Object.assign({}, DEFAULTS);
    let shownFrame = -1;     // the time effects' frame last drawn
    const stats = { uploads: 0, draws: 0 };

    glCanvas.addEventListener('webglcontextlost', (ev) => {
      ev.preventDefault();
      lost = true;
      console.warn('fmrb: CRT look: WebGL context lost');
    });

    function draw() {
      if (lost || !texW) return false;
      const W = glCanvas.width, H = glCanvas.height;
      const scale = Math.min(W / texW, H / texH);
      gl.viewport(0, 0, W, H);
      gl.uniform2f(U.u_src, texW, texH);
      gl.uniform2f(U.u_dst, W, H);
      gl.uniform1f(U.u_curve, curveCoef(settings.curve));
      gl.uniform1f(U.u_scan, settings.scan / 100 * fineWeight(scale, 1.5, 3.0));
      gl.uniform1f(U.u_mask, settings.mask / 100 * fineWeight(scale, 2.0, 3.0));
      gl.uniform1f(U.u_glow, settings.glow / 100);
      gl.uniform1f(U.u_vig, settings.vignette / 100);
      gl.uniform1f(U.u_ntsc, (settings.ntsc || 0) / 100);
      gl.uniform1f(U.u_flicker, (settings.flicker || 0) / 100);
      gl.uniform1f(U.u_noise, (settings.noise || 0) / 100);
      shownFrame = timed(settings) ? timeFrame(performance.now()) : -1;
      gl.uniform1f(U.u_frame, Math.max(shownFrame, 0));
      gl.drawArrays(gl.TRIANGLES, 0, 3);
      stats.draws++;
      return true;
    }

    return {
      get lost() { return lost; },
      stats,
      // A new picture (main.js's imageData, already copied out of the
      // SharedArrayBuffer): uploaded on the next flush.
      setImage(imageData) { pending = imageData; dirty = true; },
      setSettings(s) { settings = Object.assign({}, settings, s); dirty = true; },
      // The display canvas's pixel size changed.
      resize(w, h) {
        w = Math.max(1, Math.round(w)); h = Math.max(1, Math.round(h));
        if (glCanvas.width !== w || glCanvas.height !== h) {
          glCanvas.width = w;
          glCanvas.height = h;
          dirty = true;
        }
      },
      // Called once per animation frame; does nothing unless something
      // changed, or (flicker, noise) the time effects' frame moved on.
      flush() {
        if (lost) return false;
        if (pending) {
          const im = pending;
          pending = null;
          const data = new Uint8Array(im.data.buffer, im.data.byteOffset, im.data.byteLength);
          if (im.width !== texW || im.height !== texH) {
            texW = im.width; texH = im.height;
            gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA8, texW, texH, 0, gl.RGBA, gl.UNSIGNED_BYTE, data);
          } else {
            gl.texSubImage2D(gl.TEXTURE_2D, 0, 0, 0, texW, texH, gl.RGBA, gl.UNSIGNED_BYTE, data);
          }
          stats.uploads++;
        }
        if (!dirty && timed(settings) && timeFrame(performance.now()) !== shownFrame) dirty = true;
        if (!dirty) return false;
        dirty = false;
        return draw();
      },
      // n draws, each waited for (a one-pixel read back makes the GPU
      // finish), to time one: average milliseconds per draw. Measurement
      // only (the driver's `crt bench=N`); not counted in stats.draws.
      bench(n) {
        if (lost || !texW) return null;
        const px = new Uint8Array(4);
        const t0 = performance.now();
        for (let i = 0; i < n; i++) {
          draw();
          gl.readPixels(0, 0, 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, px);
        }
        stats.draws -= n;
        dirty = true;
        return (performance.now() - t0) / n;
      },
      // Draw now and read the canvas back in the same task (the drawing
      // buffer is not preserved past it). For the driver's `view`.
      snapshot() {
        if (pending) this.flush();
        draw();
        return glCanvas.toDataURL('image/png');
      },
    };
  }

  const api = { DEFAULTS, PRESETS, KEYS, CURVE_MAX, TIME_FPS, timed, timeFrame, warpToSource, warpToDisplay, inside, fineWeight, create };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.FmrbCrt = api;
})(typeof window !== 'undefined' ? window : globalThis);
