#!/usr/bin/env ruby
# Generate character table A (the animation characters) for FMRuby BASIC.
#
# Table A is the sprite side of the character generator (core_spec sec 12): a
# 16x16 character occupies four consecutive codes (n = top left, n+1 = top
# right, n+2 = bottom left, n+3 = bottom right), and DEF MOVE picks its frames
# by those code positions (basic_sprite.cpp anim_characters).
#
# The original machine's table holds Nintendo's artwork, which this project
# cannot ship. What follows is this project's own cast: every pixel is drawn
# here, while the *roles* and code positions follow the spec, so a program
# written for the original still animates the character it asks for -- kind 0
# is the running hero, kind 12 walks sideways like a crab, and so on. The names
# below are ours; the spec table is the map from role to code.
#
# Art format: one line per pixel row, '.' = transparent (index 0), '1'-'3' =
# the three colours of the attribute group the sprite is drawn with. The
# convention across the whole set is
#
#   1 = outline and dark detail   2 = main body colour   3 = highlight / skin
#
# so a sprite stays readable in every palette bank (the banks put a dark, a
# mid and a light colour in that order -- basic_sprite.cpp load_palette_bank).
# A sprite is cut into 8x8 tiles left to right, top to bottom, which is exactly
# the order table A assigns codes in.
#
# Usage:
#     tool/basic/gen_basic_tiles.rb [output.c]
#         default output: components/basic/assets/basic_tile_a.c
#     tool/basic/gen_basic_tiles.rb --bmp sheet.bmp
#         write the art as an editable sheet instead

