# Art text -> rows of colour indices, with the shape checked: a drawing that
# lost or gained a pixel would otherwise land silently in the wrong tile.
def parse(name, text)
  rows = text.lines.map(&:chomp).reject { |line| line.strip.empty? }
  width = rows.first.length
  bad = rows.each_with_index.reject { |line, _| line.length == width }
  unless bad.empty?
    list = bad.map { |line, y| "row #{y} is #{line.length} wide" }.join(", ")
    raise "#{name}: rows must all be #{width} wide (#{list})"
  end
  raise "#{name}: width #{width} is not a multiple of #{CELL}" if width % CELL != 0
  raise "#{name}: height #{rows.length} is not a multiple of #{CELL}" if rows.length % CELL != 0

  rows.map do |line|
    line.chars.map do |ch|
      case ch
      when "." then 0
      when "1", "2", "3" then ch.to_i
      else raise "#{name}: '#{ch}' is not a colour index"
      end
    end
  end
end

# One drawing -> its 8x8 tiles in code order (left to right, top to bottom,
# which is the order table A numbers the parts of a 16x16 character in).
def tiles(pixels)
  out = []
  (pixels.length / CELL).times do |cell_y|
    (pixels.first.length / CELL).times do |cell_x|
      out << (0...CELL).map do |y|
        row = pixels[cell_y * CELL + y]
        (0...CELL).map { |x| row[cell_x * CELL + x] }
      end
    end
  end
  out
end

# Pack one 8x8 tile into eight 2bpp rows (leftmost pixel is the top pair).
def pack(tile)
  tile.map do |row|
    row.each_with_index.reduce(0) { |bits, (index, x)| bits | (index << (14 - 2 * x)) }
  end
end

def build
  glyphs = Array.new(256) { Array.new(CELL, 0) }
  used = {}
  LAYOUT.each do |base, name|
    art = ART[name] or raise "#{name}: no art"
    tiles(parse(name, art)).each_with_index do |tile, i|
      code = base + i
      raise "#{name}: code #{code} is past the end of the table" if code > 255
      if (owner = used[code])
        raise "#{name}: code #{code} is already drawn by #{owner}"
      end
      used[code] = name
      glyphs[code] = pack(tile)
    end
  end
  glyphs
end

def emit_c(glyphs, path)
  lines = [
    "// Generated by tool/basic/gen_basic_tiles.rb -- do not edit by hand.",
    "//",
    "// Character table A (the animation characters). The code positions follow",
    "// core_spec sec 12 so DEF SPRITE / DEF MOVE animate the role a program asks",
    "// for; the artwork is this project's own (see the generator for the cast).",
    "// Two bits per pixel: the leftmost pixel is the top pair of each row.",
    "",
    '#include "basic_tile_a.h"',
    "",
    "const uint16_t basic_tile_a[256][8] = {",
  ]
  256.times do |code|
    rows = glyphs[code].map { |v| format("0x%04X", v) }.join(", ")
    lines << "    {#{rows}},  // #{code}"
  end
  lines << "};"
  lines << ""
  File.write(path, lines.join("\n"))
end

def main
  here = File.dirname(File.expand_path(__FILE__))
  args = ARGV.dup
  bmp = nil
  if (at = args.index("--bmp"))
    bmp = args[at + 1]
    args.slice!(at, 2)
  end
  glyphs = build
  if bmp
    # Export the art as an editable sheet instead of the C table. This
    # overwrites hand edits, so it is never part of the default run.
    BasicSheet.write_bmp(BasicSheet.glyphs_to_pixels(glyphs), bmp)
    puts "wrote #{bmp}"
    return
  end
  default = File.join(here, "..", "..", "components", "basic", "assets", "basic_tile_a.c")
  out = args[0] || File.expand_path(default)
  emit_c(glyphs, out)
  puts "wrote #{out}"
end

