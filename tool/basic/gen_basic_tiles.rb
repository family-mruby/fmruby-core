# Render a word as a 48x8 strip drawn in the highlight colour.
def word_strip(word)
  rows = Array.new(8) { "." * (word.length * 6) }
  word.chars.each_with_index do |ch, i|
    glyph = LETTERS.fetch(ch)
    glyph.each_with_index do |line, y|
      line.chars.each_with_index do |pixel, x|
        rows[y][i * 6 + x] = "3" if pixel == "1"
      end
    end
  end
  rows.join("\n") + "\n"
end

