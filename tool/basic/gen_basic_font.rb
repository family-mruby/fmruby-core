# Turn one art string into eight row bytes (bit 7 = leftmost pixel).
def parse_art(art)
  rows = art.split
  raise "glyph needs 8 rows, got #{rows.length}: #{art.inspect}" unless rows.length == 8
  rows.map do |row|
    raise "row needs 8 columns: #{row.inspect}" unless row.length == 8
    value = 0
    row.each_char.with_index do |ch, bit|
      case ch
      when "#" then value |= 0x80 >> bit
      when "." then nil
      else raise "row uses '#' and '.' only: #{row.inspect}"
      end
    end
    value
  end
end

# Placeholder artwork for the background pattern codes (184-255).
#
# The real set is drawn in B3 together with the tile sheet; until then each
# code gets a distinguishable geometric pattern so a screen full of them is
# still readable on a screenshot.
def bg_pattern(code)
  kind = (code - 0xB8) % 8
  (0...8).map do |y|
    case kind
    when 0 then y.even? ? 0xFF : 0x00        # horizontal stripes
    when 1 then 0xAA                          # vertical stripes
    when 2 then [0, 7].include?(y) ? 0xFF : 0x81  # frame
    when 3 then 0xFF                          # solid
    when 4 then (2..5).cover?(y) ? 0x18 : 0x00    # centre block
    when 5 then (y % 4 < 2) ? 0xCC : 0x33     # checker
    when 6 then 0x01 << (y % 8)               # diagonal
    else 0x00                                  # half tone (top half blank)
    end
  end.each_with_index.map { |v, y| kind == 7 ? (y < 4 ? 0x00 : 0xFF) : v }
end

def build
  glyphs = Array.new(256) { Array.new(8, 0) }

  [ASCII_ART, KANA_ART, SYMBOL_ART].each do |table|
    table.each { |code, art| glyphs[code] = parse_art(art) }
  end

  # Voiced marks: shift the base kana down one row and put the mark on the row
  # that frees up. OR-ing the mark into the corner of the base does not work --
  # 16 of the 20 bases already draw there, so the mark merged into the glyph
  # and disappeared (GA differed from KA by two pixels). Shifting costs those
  # glyphs the blank bottom row, which is a line gap, not part of the shape.
  DAKUTEN.each { |code, base| glyphs[code] = [0x0A] + glyphs[base][0, 7] }      # two dots
  HANDAKUTEN.each { |code, base| glyphs[code] = [0x04] + glyphs[base][0, 7] }   # one dot

  (0xB8...0x100).each { |code| glyphs[code] = bg_pattern(code) }

  # 0-31 are the BG graphic groups the system reserves (core_spec sec 12):
  # leave them blank until B3 defines the tile set.
  glyphs
end

def emit_c(glyphs, path)
  lines = []
  lines << "// Generated by tool/basic/gen_basic_font.rb -- do not edit by hand."
  lines << "//"
  lines << "// FMRuby BASIC 8x8 text font. Code positions follow the Family BASIC"
  lines << "// character table (core_spec sec 12); the shapes are original artwork for"
  lines << "// this project. Bit 7 of each byte is the leftmost pixel."
  lines << ""
  lines << '#include "basic_font8.h"'
  lines << ""
  lines << "const uint8_t basic_font8[256][8] = {"
  256.times do |code|
    rows = glyphs[code].map { |v| format("0x%02X", v) }.join(", ")
    lines << "    {#{rows}},  // #{code}"
  end
  lines << "};"
  lines << ""
  File.write(path, lines.join("\n"))
end

def main
  here = File.dirname(File.expand_path(__FILE__))
  args = ARGV.dup
  bmp = nil
  if (at = args.index("--bmp"))
    bmp = args[at + 1]
    args.slice!(at, 2)
  end
  glyphs = build
  if bmp
    # Export the art as an editable sheet instead of the C table. This
    # overwrites hand edits, so it is never part of the default run.
    BasicSheet.write_bmp(BasicSheet.glyphs_to_pixels(glyphs), bmp)
    puts "wrote #{bmp}"
    return
  end
  default = File.join(here, "..", "..", "components", "basic", "assets", "basic_font8.c")
  out = args[0] || File.expand_path(default)
  emit_c(glyphs, out)
  puts "wrote #{out}"
end

main if __FILE__ == $PROGRAM_NAME
